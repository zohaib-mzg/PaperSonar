-- PaperSonar Phase 2 - READ-ONLY verification SQL for Snowflake Worksheet.
-- Run each numbered SELECT separately. Save results with execution date,
-- database/role/warehouse, and query ID (do NOT include credentials).
-- Counts below must be taken from live Snowflake; no values are assumed.

-- 01. Exact row counts: >=100 dimension records and >=10,000 FACT records.
-- Unknown dimension members count as rows; show both total and usable rows.
SELECT 'DIM_WORK' AS OBJECT_NAME, COUNT(*) AS TOTAL_ROWS, COUNT_IF(WORK_KEY IS NOT NULL) AS USABLE_ROWS
FROM PROJECT_DW.DIM_WORK
UNION ALL SELECT 'DIM_DATE', COUNT(*), COUNT_IF(DATE_KEY <> 0) FROM PROJECT_DW.DIM_DATE
UNION ALL SELECT 'DIM_TOPIC', COUNT(*), COUNT_IF(TOPIC_KEY <> '-1') FROM PROJECT_DW.DIM_TOPIC
UNION ALL SELECT 'DIM_VENUE', COUNT(*), COUNT_IF(VENUE_KEY <> '-1') FROM PROJECT_DW.DIM_VENUE
UNION ALL SELECT 'DIM_WORK_TYPE', COUNT(*), COUNT_IF(WORK_TYPE_KEY <> '-1') FROM PROJECT_DW.DIM_WORK_TYPE
UNION ALL SELECT 'DIM_ACCESS_STATUS', COUNT(*), COUNT_IF(ACCESS_STATUS_KEY <> '-1') FROM PROJECT_DW.DIM_ACCESS_STATUS
UNION ALL SELECT 'DIM_AUTHOR', COUNT(*), COUNT_IF(AUTHOR_KEY <> '-1') FROM PROJECT_DW.DIM_AUTHOR
UNION ALL SELECT 'DIM_INSTITUTION', COUNT(*), COUNT_IF(INSTITUTION_KEY <> '-1') FROM PROJECT_DW.DIM_INSTITUTION
UNION ALL SELECT 'FACT_PUBLICATION', COUNT(*), COUNT(*) FROM PROJECT_DW.FACT_PUBLICATION
UNION ALL SELECT 'FACT_WORK_SNAPSHOT', COUNT(*), COUNT(*) FROM PROJECT_DW.FACT_WORK_SNAPSHOT
UNION ALL SELECT 'FACT_CITATION', COUNT(*), COUNT(*) FROM PROJECT_DW.FACT_CITATION
ORDER BY OBJECT_NAME;

-- 02. Numeric surrogate-key completeness and uniqueness after migration 005.
-- Every missing count and duplicate count must be 0. Check map uniqueness too;
-- Snowflake standard-table PK constraints are informational, not enforcement.
SELECT 'DIM_WORK_NULL_SK' AS CHECK_NAME, COUNT(*) AS ROWS_FOUND
FROM PROJECT_DW.DIM_WORK WHERE WORK_SK IS NULL
UNION ALL SELECT 'DIM_DATE_NULL_SK', COUNT(*) FROM PROJECT_DW.DIM_DATE WHERE DATE_SK IS NULL
UNION ALL SELECT 'DIM_TOPIC_NULL_SK', COUNT(*) FROM PROJECT_DW.DIM_TOPIC WHERE TOPIC_SK IS NULL
UNION ALL SELECT 'DIM_VENUE_NULL_SK', COUNT(*) FROM PROJECT_DW.DIM_VENUE WHERE VENUE_SK IS NULL
UNION ALL SELECT 'DIM_WORK_TYPE_NULL_SK', COUNT(*) FROM PROJECT_DW.DIM_WORK_TYPE WHERE WORK_TYPE_SK IS NULL
UNION ALL SELECT 'DIM_ACCESS_STATUS_NULL_SK', COUNT(*) FROM PROJECT_DW.DIM_ACCESS_STATUS WHERE ACCESS_STATUS_SK IS NULL
UNION ALL SELECT 'DIM_AUTHOR_NULL_SK', COUNT(*) FROM PROJECT_DW.DIM_AUTHOR WHERE AUTHOR_SK IS NULL
UNION ALL SELECT 'DIM_INSTITUTION_NULL_SK', COUNT(*) FROM PROJECT_DW.DIM_INSTITUTION WHERE INSTITUTION_SK IS NULL
UNION ALL SELECT 'FACT_PUBLICATION_NULL_SK', COUNT(*) FROM PROJECT_DW.FACT_PUBLICATION
WHERE WORK_SK IS NULL OR PUBLICATION_DATE_SK IS NULL OR WORK_TYPE_SK IS NULL
   OR VENUE_SK IS NULL OR ACCESS_STATUS_SK IS NULL
UNION ALL SELECT 'FACT_SNAPSHOT_NULL_SK', COUNT(*) FROM PROJECT_DW.FACT_WORK_SNAPSHOT
WHERE WORK_SK IS NULL OR SNAPSHOT_DATE_SK IS NULL OR ACCESS_STATUS_SK IS NULL
UNION ALL SELECT 'FACT_CITATION_NULL_CITING_SK', COUNT(*) FROM PROJECT_DW.FACT_CITATION WHERE WORK_SK IS NULL
UNION ALL SELECT 'FACT_CITATION_RESOLVED_NULL_CITED_SK', COUNT(*) FROM PROJECT_DW.FACT_CITATION
WHERE CITED_WORK_KEY != '' AND CITED_WORK_SK IS NULL
UNION ALL SELECT 'BRIDGE_TOPIC_NULL_SK', COUNT(*) FROM PROJECT_DW.BRIDGE_WORK_TOPIC
WHERE WORK_SK IS NULL OR TOPIC_SK IS NULL
UNION ALL SELECT 'BRIDGE_AUTHOR_NULL_SK', COUNT(*) FROM PROJECT_DW.BRIDGE_WORK_AUTHOR
WHERE WORK_SK IS NULL OR AUTHOR_SK IS NULL
UNION ALL SELECT 'BRIDGE_INSTITUTION_NULL_SK', COUNT(*) FROM PROJECT_DW.BRIDGE_WORK_INSTITUTION
WHERE WORK_SK IS NULL OR INSTITUTION_SK IS NULL OR AUTHOR_SK IS NULL
UNION ALL SELECT 'KEY_MAP_DUPLICATE_BUSINESS_KEY', COUNT(*) FROM (
  SELECT DIMENSION_NAME, BUSINESS_KEY FROM PROJECT_DW.DIMENSION_KEY_MAP
  GROUP BY DIMENSION_NAME, BUSINESS_KEY HAVING COUNT(*) > 1
)
UNION ALL SELECT 'KEY_MAP_DUPLICATE_SURROGATE_KEY', COUNT(*) FROM (
  SELECT SURROGATE_KEY FROM PROJECT_DW.DIMENSION_KEY_MAP
  GROUP BY SURROGATE_KEY HAVING COUNT(*) > 1
);

-- 03. Staging cleaning: accepted/quarantined, missingness, partial dates.
SELECT SOURCE_NAME, VALIDATION_STATUS,
       COUNT(*) AS ROWS,
       COUNT_IF(DOI_NORMALIZED IS NULL) AS DOI_NULL,
       COUNT_IF(TITLE_NORMALIZED IS NULL) AS TITLE_NULL,
       COUNT_IF(PUBLICATION_YEAR IS NULL) AS YEAR_NULL,
       COUNT_IF(PUBLICATION_DATE IS NOT NULL AND LENGTH(PUBLICATION_DATE) < 10)
         AS PARTIAL_PUBLICATION_DATES,
       COUNT_IF(TITLE IS NOT NULL AND TITLE <> TRIM(TITLE)) AS TITLES_WITH_OUTER_SPACE
FROM PROJECT_STAGING.STG_WORK_RECORD
GROUP BY SOURCE_NAME, VALIDATION_STATUS
ORDER BY SOURCE_NAME, VALIDATION_STATUS;

-- 04. Invalid identifier, rejected row reasons and resolutions.
SELECT SOURCE_NAME, REASON_CODE, RESOLUTION_STATUS, COUNT(*) AS ROWS
FROM PROJECT_STAGING.STG_QUARANTINE
GROUP BY SOURCE_NAME, REASON_CODE, RESOLUTION_STATUS
ORDER BY ROWS DESC;

-- 05. Staging content-key uniqueness (expected zero rows).
SELECT SOURCE_NAME, SOURCE_RECORD_ID, PAYLOAD_SHA256, COUNT(*) AS DUPLICATES
FROM PROJECT_STAGING.STG_WORK_RECORD
GROUP BY 1, 2, 3 HAVING COUNT(*) > 1 ORDER BY DUPLICATES DESC;

-- 06. Canonical key uniqueness (expected zero rows).
SELECT WORK_KEY, COUNT(*) AS DUPLICATES
FROM PROJECT_DW.DIM_WORK
GROUP BY WORK_KEY HAVING COUNT(*) > 1 ORDER BY DUPLICATES DESC;

-- 07. Publication fact grain uniqueness (expected zero rows).
SELECT WORK_KEY, COUNT(*) AS DUPLICATES
FROM PROJECT_DW.FACT_PUBLICATION
GROUP BY WORK_KEY HAVING COUNT(*) > 1 ORDER BY DUPLICATES DESC;

-- 08. Snapshot grain uniqueness (expected zero rows).
SELECT WORK_KEY, SNAPSHOT_DATE_KEY, COUNT(*) AS DUPLICATES
FROM PROJECT_DW.FACT_WORK_SNAPSHOT
GROUP BY 1, 2 HAVING COUNT(*) > 1 ORDER BY DUPLICATES DESC;

-- 09. Fact references to dimensions: target is 0 orphan rows per foreign-key.
SELECT 'PUBLICATION_TO_WORK' AS CHECK_NAME, COUNT(*) AS ORPHAN_ROWS
FROM PROJECT_DW.FACT_PUBLICATION f LEFT JOIN PROJECT_DW.DIM_WORK d ON f.WORK_KEY = d.WORK_KEY
WHERE d.WORK_KEY IS NULL
UNION ALL SELECT 'PUBLICATION_TO_TYPE', COUNT(*)
FROM PROJECT_DW.FACT_PUBLICATION f LEFT JOIN PROJECT_DW.DIM_WORK_TYPE d ON f.WORK_TYPE_KEY = d.WORK_TYPE_KEY
WHERE d.WORK_TYPE_KEY IS NULL
UNION ALL SELECT 'PUBLICATION_TO_VENUE', COUNT(*)
FROM PROJECT_DW.FACT_PUBLICATION f LEFT JOIN PROJECT_DW.DIM_VENUE d ON f.VENUE_KEY = d.VENUE_KEY
WHERE d.VENUE_KEY IS NULL
UNION ALL SELECT 'PUBLICATION_TO_ACCESS', COUNT(*)
FROM PROJECT_DW.FACT_PUBLICATION f LEFT JOIN PROJECT_DW.DIM_ACCESS_STATUS d
ON f.ACCESS_STATUS_KEY = d.ACCESS_STATUS_KEY WHERE d.ACCESS_STATUS_KEY IS NULL
UNION ALL SELECT 'SNAPSHOT_TO_WORK', COUNT(*)
FROM PROJECT_DW.FACT_WORK_SNAPSHOT f LEFT JOIN PROJECT_DW.DIM_WORK d ON f.WORK_KEY = d.WORK_KEY
WHERE d.WORK_KEY IS NULL
UNION ALL SELECT 'CITATION_CITING_TO_WORK', COUNT(*)
FROM PROJECT_DW.FACT_CITATION f LEFT JOIN PROJECT_DW.DIM_WORK d ON f.WORK_KEY = d.WORK_KEY
WHERE d.WORK_KEY IS NULL;

-- 10. Count reconciliation (not necessarily equal due to deduplication).
SELECT 'STAGING_ACCEPTED' AS METRIC, COUNT(*) AS ROWS
FROM PROJECT_STAGING.STG_WORK_RECORD WHERE VALIDATION_STATUS = 'accepted'
UNION ALL SELECT 'CROSSWALK', COUNT(*) FROM PROJECT_DW.WORK_SOURCE_XW
UNION ALL SELECT 'CANONICAL_WORKS', COUNT(*) FROM PROJECT_DW.DIM_WORK
UNION ALL SELECT 'PUBLICATION_FACTS', COUNT(*) FROM PROJECT_DW.FACT_PUBLICATION
UNION ALL SELECT 'RAW_BATCHES', COUNT(*) FROM PROJECT_OPS.RAW_BATCH;

-- 11. Source sync history and stale error diagnostics.
SELECT SOURCE_NAME, STREAM_NAME, STATUS, PAGES_COMPLETED, RECORDS_SEEN,
       RECORDS_WRITTEN, LAST_SUCCESSFUL_WATERMARK, CURSOR_OR_TOKEN,
       LAST_ATTEMPT_AT, LAST_SUCCESS_AT, ERROR_CODE, ERROR_SUMMARY
FROM PROJECT_OPS.SOURCE_SYNC_STATE
ORDER BY LAST_ATTEMPT_AT DESC LIMIT 100;

-- 12. Latest run outcomes and duration.
SELECT RUN_ID, MODE, STATUS, STARTED_AT, FINISHED_AT,
       DATEDIFF('minute', STARTED_AT, COALESCE(FINISHED_AT, CURRENT_TIMESTAMP())) AS ELAPSED_MIN,
       RAW_ROWS, STAGING_ROWS, QUARANTINED_ROWS, WAREHOUSE_ROWS,
       QUALITY_GATE_RESULT, ERROR_SUMMARY
FROM PROJECT_OPS.ETL_RUN ORDER BY STARTED_AT DESC LIMIT 30;

-- 13. Verify migrations (004 changed PUBLICATION_DATE to text).
SELECT MIGRATION_ID, APPLIED_AT FROM PROJECT_OPS.SCHEMA_MIGRATION ORDER BY MIGRATION_ID;

-- 14. Verify source distribution of publication facts.
SELECT SOURCE_PRIORITY, COUNT(*) AS PUBLICATION_FACTS
FROM PROJECT_DW.FACT_PUBLICATION GROUP BY SOURCE_PRIORITY ORDER BY PUBLICATION_FACTS DESC;

-- 15. Quantify data-quality gate coverage and logical validation thresholds.
SELECT COUNT(*) AS TOTAL_STAGING_ROWS,
       COUNT_IF(VALIDATION_STATUS = 'accepted') AS ACCEPTED_ROWS,
       COUNT_IF(VALIDATION_STATUS <> 'accepted') AS NON_ACCEPTED_ROWS,
       COUNT_IF(SOURCE_RECORD_ID IS NULL OR TRIM(SOURCE_RECORD_ID) = '') AS MISSING_SOURCE_IDS,
       COUNT_IF(CITED_BY_COUNT < 0) AS NEGATIVE_CITATIONS
FROM PROJECT_STAGING.STG_WORK_RECORD;

-- 16. Orphaned in-progress state after a 120-minute GitHub job timeout.
-- GitHub enforces its 120-minute job limit; the process may not have time
-- to mark ETL_RUN failed on forced cancellation, so detect stale STARTED rows.
SELECT RUN_ID, STATUS, STARTED_AT,
       DATEDIFF('minute', STARTED_AT, CURRENT_TIMESTAMP()) AS MINUTES_RUNNING
FROM PROJECT_OPS.ETL_RUN
WHERE STATUS = 'started' AND STARTED_AT < DATEADD(minute, -120, CURRENT_TIMESTAMP())
ORDER BY STARTED_AT;

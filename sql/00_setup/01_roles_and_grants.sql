-- =============================================================================
-- Purpose: Create the four Phase 2 roles and grant least-privilege access.
-- Inputs: PAPERSONAR_ADMIN hierarchy created by an account administrator.
-- Outputs: PAPERSONAR_ADMIN, PAPERSONAR_LOADER, PAPERSONAR_TRANSFORMER,
--          PAPERSONAR_REPORTER and schema/object grants.
-- Idempotent: Yes - CREATE ROLE IF NOT EXISTS and additive grants.
-- Owner: PAPERSONAR_ADMIN
-- Parameters: None.
-- Cost: Metadata operation only.
-- =============================================================================
-- VERIFY: executing GRANT ... ON ACCOUNT (EXECUTE TASK) requires ACCOUNTADMIN
-- or a role with MANAGE GRANTS. Run this file with an administrative role, then
-- switch to PAPERSONAR_ADMIN for normal work. Automation must never use
-- ACCOUNTADMIN.
--
-- Run order: 00 schemas -> 02 warehouse -> 03 stages -> 04 audit DDL ->
-- 05 reference DDL -> 06 seeds -> this file. The loader grants below reference
-- tables and stages created by those files. Future-table grants cover objects
-- created by the later transformation deployment.

CREATE ROLE IF NOT EXISTS PAPERSONAR_ADMIN
  COMMENT = 'Controlled setup, grants, warehouse and resource controls';
CREATE ROLE IF NOT EXISTS PAPERSONAR_LOADER
  COMMENT = 'Stage upload and manifest registration only';
CREATE ROLE IF NOT EXISTS PAPERSONAR_TRANSFORMER
  COMMENT = 'Task graph execution and warehouse transformations';
CREATE ROLE IF NOT EXISTS PAPERSONAR_REPORTER
  COMMENT = 'Read-only access to approved reporting views';

-- Role hierarchy: admin owns the graph; loader and transformer stay separate.
GRANT ROLE PAPERSONAR_ADMIN TO ROLE SYSADMIN;
GRANT ROLE PAPERSONAR_LOADER TO ROLE PAPERSONAR_ADMIN;
GRANT ROLE PAPERSONAR_TRANSFORMER TO ROLE PAPERSONAR_ADMIN;
GRANT ROLE PAPERSONAR_REPORTER TO ROLE PAPERSONAR_ADMIN;

GRANT USAGE ON DATABASE PAPERSONAR TO ROLE PAPERSONAR_ADMIN;
GRANT ALL PRIVILEGES ON ALL SCHEMAS IN DATABASE PAPERSONAR TO ROLE PAPERSONAR_ADMIN;
GRANT ALL PRIVILEGES ON FUTURE SCHEMAS IN DATABASE PAPERSONAR TO ROLE PAPERSONAR_ADMIN;

-- Loader: stage upload, batch/manifest/quarantine registration, verification.
GRANT USAGE ON DATABASE PAPERSONAR TO ROLE PAPERSONAR_LOADER;
GRANT USAGE ON SCHEMA PAPERSONAR.PROJECT_STAGING TO ROLE PAPERSONAR_LOADER;
GRANT USAGE ON SCHEMA PAPERSONAR.PROJECT_AUDIT TO ROLE PAPERSONAR_LOADER;
GRANT READ, WRITE ON STAGE PAPERSONAR.PROJECT_STAGING.RAW_STAGE TO ROLE PAPERSONAR_LOADER;
GRANT SELECT ON TABLE PAPERSONAR.PROJECT_AUDIT.BATCH TO ROLE PAPERSONAR_LOADER;
GRANT INSERT, UPDATE ON TABLE PAPERSONAR.PROJECT_AUDIT.BATCH TO ROLE PAPERSONAR_LOADER;
GRANT SELECT ON TABLE PAPERSONAR.PROJECT_AUDIT.BATCH_MANIFEST TO ROLE PAPERSONAR_LOADER;
GRANT INSERT, UPDATE ON TABLE PAPERSONAR.PROJECT_AUDIT.BATCH_MANIFEST TO ROLE PAPERSONAR_LOADER;
GRANT SELECT ON TABLE PAPERSONAR.PROJECT_AUDIT.SOURCE_WATERMARK TO ROLE PAPERSONAR_LOADER;
GRANT INSERT ON TABLE PAPERSONAR.PROJECT_AUDIT.QUARANTINE_RECORD TO ROLE PAPERSONAR_LOADER;
GRANT USAGE ON WAREHOUSE WH_PAPERSONAR_ELT TO ROLE PAPERSONAR_LOADER;
GRANT EXECUTE TASK ON ACCOUNT TO ROLE PAPERSONAR_LOADER;

-- Transformer: read staging/audit, write every analytical layer, run tasks.
GRANT USAGE ON DATABASE PAPERSONAR TO ROLE PAPERSONAR_TRANSFORMER;
GRANT USAGE ON ALL SCHEMAS IN DATABASE PAPERSONAR TO ROLE PAPERSONAR_TRANSFORMER;
GRANT USAGE ON FUTURE SCHEMAS IN DATABASE PAPERSONAR TO ROLE PAPERSONAR_TRANSFORMER;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA PAPERSONAR.PROJECT_STAGING
  TO ROLE PAPERSONAR_TRANSFORMER;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA PAPERSONAR.PROJECT_BRONZE
  TO ROLE PAPERSONAR_TRANSFORMER;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA PAPERSONAR.PROJECT_SILVER
  TO ROLE PAPERSONAR_TRANSFORMER;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA PAPERSONAR.PROJECT_DW
  TO ROLE PAPERSONAR_TRANSFORMER;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA PAPERSONAR.PROJECT_AUDIT
  TO ROLE PAPERSONAR_TRANSFORMER;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA PAPERSONAR.PROJECT_REF
  TO ROLE PAPERSONAR_TRANSFORMER;
GRANT SELECT, INSERT, UPDATE, DELETE ON FUTURE TABLES IN SCHEMA PAPERSONAR.PROJECT_STAGING
  TO ROLE PAPERSONAR_TRANSFORMER;
GRANT SELECT, INSERT, UPDATE, DELETE ON FUTURE TABLES IN SCHEMA PAPERSONAR.PROJECT_BRONZE
  TO ROLE PAPERSONAR_TRANSFORMER;
GRANT SELECT, INSERT, UPDATE, DELETE ON FUTURE TABLES IN SCHEMA PAPERSONAR.PROJECT_SILVER
  TO ROLE PAPERSONAR_TRANSFORMER;
GRANT SELECT, INSERT, UPDATE, DELETE ON FUTURE TABLES IN SCHEMA PAPERSONAR.PROJECT_DW
  TO ROLE PAPERSONAR_TRANSFORMER;
GRANT SELECT, INSERT, UPDATE, DELETE ON FUTURE TABLES IN SCHEMA PAPERSONAR.PROJECT_AUDIT
  TO ROLE PAPERSONAR_TRANSFORMER;
GRANT SELECT, INSERT, UPDATE, DELETE ON FUTURE TABLES IN SCHEMA PAPERSONAR.PROJECT_REF
  TO ROLE PAPERSONAR_TRANSFORMER;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA PAPERSONAR.PROJECT_DW TO ROLE PAPERSONAR_TRANSFORMER;
GRANT USAGE ON FUTURE SEQUENCES IN SCHEMA PAPERSONAR.PROJECT_DW TO ROLE PAPERSONAR_TRANSFORMER;
GRANT READ ON STAGE PAPERSONAR.PROJECT_STAGING.RAW_STAGE TO ROLE PAPERSONAR_TRANSFORMER;
GRANT USAGE ON WAREHOUSE WH_PAPERSONAR_ELT TO ROLE PAPERSONAR_TRANSFORMER;
GRANT EXECUTE TASK ON ACCOUNT TO ROLE PAPERSONAR_TRANSFORMER;
GRANT EXECUTE TASK ON ACCOUNT TO ROLE PAPERSONAR_ADMIN;

-- Reporter: read-only access to the reporting schema.
GRANT USAGE ON DATABASE PAPERSONAR TO ROLE PAPERSONAR_REPORTER;
GRANT USAGE ON SCHEMA PAPERSONAR.PROJECT_REPORTING TO ROLE PAPERSONAR_REPORTER;
GRANT SELECT ON ALL VIEWS IN SCHEMA PAPERSONAR.PROJECT_REPORTING TO ROLE PAPERSONAR_REPORTER;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA PAPERSONAR.PROJECT_REPORTING TO ROLE PAPERSONAR_REPORTER;
GRANT USAGE ON WAREHOUSE WH_PAPERSONAR_ELT TO ROLE PAPERSONAR_REPORTER;

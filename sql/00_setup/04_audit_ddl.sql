-- =============================================================================
-- Purpose: Create the audit, batch-lifecycle, manifest, watermark, DQ,
--          quarantine and lineage tables required by the Phase 2 contract.
-- Inputs: PAPERSONAR.PROJECT_AUDIT schema.
-- Outputs: BATCH, BATCH_MANIFEST, SOURCE_WATERMARK, RUN_LOG, DQ_RESULT,
--          SCHEMA_DRIFT_LOG, QUARANTINE_RECORD, FILE_LOAD_LOG, LINEAGE_EVENT,
--          CURRENT_BATCH and PUBLISHED_BATCH (including IS_CAPPED audit flags).
-- Idempotent: Yes - CREATE TABLE IF NOT EXISTS only.
-- Owner: PAPERSONAR_ADMIN
-- Parameters: None.
-- Cost: Metadata only; audit rows are small compared with raw payloads.
-- =============================================================================
-- Constraints are declared as useful metadata only; Snowflake does not enforce
-- standard-table primary/unique keys. Loading logic and DQ SQL enforce grain.

CREATE TABLE IF NOT EXISTS PAPERSONAR.PROJECT_AUDIT.BATCH (
  BATCH_ID           VARCHAR(64)  NOT NULL,
  SOURCE_NAME        VARCHAR(50)  NOT NULL,
  ENTITY_NAME        VARCHAR(50)  NOT NULL,
  EXTRACTION_MODE    VARCHAR(20)  NOT NULL,
  WINDOW_START       DATE         NOT NULL,
  WINDOW_END         DATE         NOT NULL,
  STATUS             VARCHAR(20)  NOT NULL,  -- EXTRACTING/LOADED/PROCESSING/PUBLISHED/FAILED
  CURSOR_START       VARCHAR(2000),
  CURSOR_END         VARCHAR(2000),
  FILE_COUNT         NUMBER(38,0) DEFAULT 0,
  RECORD_COUNT       NUMBER(38,0) DEFAULT 0,
  CLAIMED_AT         TIMESTAMP_NTZ,
  CLAIMED_BY         VARCHAR(200),
  IS_CAPPED          BOOLEAN DEFAULT FALSE,  -- TRUE when max_records stopped the window early
  STARTED_AT         TIMESTAMP_NTZ,
  FINISHED_AT        TIMESTAMP_NTZ,
  ERROR_SUMMARY      VARCHAR(2000),
  CREATED_AT         TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  UPDATED_AT         TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  CONSTRAINT PK_BATCH PRIMARY KEY (BATCH_ID)
)
COMMENT = 'One row per logical extraction window and its lifecycle state';

CREATE TABLE IF NOT EXISTS PAPERSONAR.PROJECT_AUDIT.BATCH_MANIFEST (
  BATCH_ID           VARCHAR(64)  NOT NULL,
  SOURCE_NAME        VARCHAR(50)  NOT NULL,
  ENTITY_NAME        VARCHAR(50)  NOT NULL,
  FILE_NAME          VARCHAR(1000) NOT NULL,
  CHECKSUM           VARCHAR(64)  NOT NULL,
  FILE_SIZE_BYTES    NUMBER(38,0) NOT NULL,
  RECORD_COUNT       NUMBER(38,0) NOT NULL,
  WINDOW_START       DATE         NOT NULL,
  WINDOW_END         DATE         NOT NULL,
  CURSOR_START       VARCHAR(2000),
  CURSOR_END         VARCHAR(2000),
  EXTRACTED_AT       TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  STATUS             VARCHAR(20)  DEFAULT 'REGISTERED',  -- REGISTERED/LOADED/FAILED
  LOADED_AT          TIMESTAMP_NTZ,
  CONSTRAINT PK_BATCH_MANIFEST PRIMARY KEY (BATCH_ID, FILE_NAME)
)
COMMENT = 'One row per source/entity/file extraction unit';

CREATE TABLE IF NOT EXISTS PAPERSONAR.PROJECT_AUDIT.SOURCE_WATERMARK (
  SOURCE_NAME        VARCHAR(50)  NOT NULL,
  ENTITY_NAME        VARCHAR(50)  NOT NULL,
  WATERMARK_VALUE    VARCHAR(100),
  WINDOW_START       DATE,
  WINDOW_END         DATE,
  OVERLAP_DAYS       NUMBER(38,0),
  CURSOR             VARCHAR(2000),
  LAST_BATCH_ID      VARCHAR(64),
  LAST_SUCCESS_AT    TIMESTAMP_NTZ,
  STATUS             VARCHAR(20),
  UPDATED_AT         TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  CONSTRAINT PK_SOURCE_WATERMARK PRIMARY KEY (SOURCE_NAME, ENTITY_NAME)
)
COMMENT = 'Watermark advances only after complete-window publication';

CREATE TABLE IF NOT EXISTS PAPERSONAR.PROJECT_AUDIT.RUN_LOG (
  RUN_ID             VARCHAR(64)  NOT NULL,
  BATCH_ID           VARCHAR(64),
  STAGE              VARCHAR(50)  NOT NULL,
  STARTED_AT         TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  FINISHED_AT        TIMESTAMP_NTZ,
  STATUS             VARCHAR(20)  NOT NULL,
  QUERY_ID           VARCHAR(100),
  WAREHOUSE          VARCHAR(100),
  ROW_COUNT          NUMBER(38,0),
  RETRY_COUNT        NUMBER(38,0) DEFAULT 0,
  ERROR_SUMMARY      VARCHAR(2000),
  IMPLEMENTATION_VERSION VARCHAR(50),
  CONSTRAINT PK_RUN_LOG PRIMARY KEY (RUN_ID)
)
COMMENT = 'One row per pipeline stage execution';

CREATE TABLE IF NOT EXISTS PAPERSONAR.PROJECT_AUDIT.DQ_RESULT (
  DQ_RESULT_ID       VARCHAR(100) NOT NULL,
  BATCH_ID           VARCHAR(64)  NOT NULL,
  RULE_ID            VARCHAR(20)  NOT NULL,
  RULE_VERSION       VARCHAR(20),
  LAYER              VARCHAR(30),
  SEVERITY           VARCHAR(10)  NOT NULL,
  DESCRIPTION        VARCHAR(1000),
  OBSERVED_VALUE     NUMBER(38,6),
  THRESHOLD_VALUE    NUMBER(38,6),
  STATUS             VARCHAR(10)  NOT NULL,  -- PASS/FAIL
  QUERY_ID           VARCHAR(100),
  CHECKED_AT         TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  CONSTRAINT PK_DQ_RESULT PRIMARY KEY (DQ_RESULT_ID)
)
COMMENT = 'Versioned data-quality checks and publication gate evidence';

CREATE TABLE IF NOT EXISTS PAPERSONAR.PROJECT_AUDIT.SCHEMA_DRIFT_LOG (
  DRIFT_ID           VARCHAR(100) NOT NULL,
  BATCH_ID           VARCHAR(64),
  SOURCE_NAME        VARCHAR(50),
  ENTITY_NAME        VARCHAR(50),
  KEY_NAME           VARCHAR(200),
  DRIFT_TYPE         VARCHAR(30),  -- NEW_KEY/MISSING_REQUIRED
  IS_REQUIRED        BOOLEAN,
  FIRST_SEEN_AT      TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  CONSTRAINT PK_SCHEMA_DRIFT_LOG PRIMARY KEY (DRIFT_ID)
)
COMMENT = 'Explicit expected-key drift; critical required-key loss blocks publication';

CREATE TABLE IF NOT EXISTS PAPERSONAR.PROJECT_AUDIT.QUARANTINE_RECORD (
  QUARANTINE_ID      VARCHAR(255) NOT NULL,
  BATCH_ID           VARCHAR(64),
  SOURCE_NAME        VARCHAR(50),
  ENTITY_NAME        VARCHAR(50),
  SOURCE_RECORD_ID   VARCHAR(1000),
  RECORD_HASH        VARCHAR(64),
  REASON_CODE        VARCHAR(40)  NOT NULL,
  DETAIL             VARIANT,
  RAW_REFERENCE      VARCHAR(1000),
  CREATED_AT         TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  CONSTRAINT PK_QUARANTINE_RECORD PRIMARY KEY (QUARANTINE_ID)
)
COMMENT = 'Malformed/invalid/oversize records are visible, never silently dropped';

CREATE TABLE IF NOT EXISTS PAPERSONAR.PROJECT_AUDIT.FILE_LOAD_LOG (
  FILE_LOAD_ID       VARCHAR(1000) NOT NULL,
  BATCH_ID           VARCHAR(64)   NOT NULL,
  SOURCE_NAME        VARCHAR(50),
  ENTITY_NAME        VARCHAR(50),
  FILE_NAME          VARCHAR(1000),
  STAGED_ROWS        NUMBER(38,0),
  MANIFEST_ROWS      NUMBER(38,0),
  STATUS             VARCHAR(20),
  LOADED_AT          TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  CONSTRAINT PK_FILE_LOAD_LOG PRIMARY KEY (FILE_LOAD_ID)
)
COMMENT = 'COPY reconciliation per registered file';

CREATE TABLE IF NOT EXISTS PAPERSONAR.PROJECT_AUDIT.LINEAGE_EVENT (
  EVENT_ID           VARCHAR(100) NOT NULL,
  BATCH_ID           VARCHAR(64),
  LAYER              VARCHAR(30),
  OBJECT_NAME        VARCHAR(200),
  EVENT_TYPE         VARCHAR(50),
  INPUT_COUNT        NUMBER(38,0),
  OUTPUT_COUNT       NUMBER(38,0),
  QUERY_ID           VARCHAR(100),
  EVENT_AT           TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  DETAILS            VARIANT,
  CONSTRAINT PK_LINEAGE_EVENT PRIMARY KEY (EVENT_ID)
)
COMMENT = 'Queryable source-to-canonical lineage evidence';

CREATE TABLE IF NOT EXISTS PAPERSONAR.PROJECT_AUDIT.CURRENT_BATCH (
  BATCH_ID           VARCHAR(64) NOT NULL,
  CLAIMED_AT         TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
)
COMMENT = 'Single-row control table for the active task-graph batch';

CREATE TABLE IF NOT EXISTS PAPERSONAR.PROJECT_AUDIT.PUBLISHED_BATCH (
  BATCH_ID           VARCHAR(64) NOT NULL,
  PUBLISHED_AT       TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  PUBLISHED_BY       VARCHAR(200),
  DQ_SUMMARY         VARCHAR(2000),
  IS_CAPPED          BOOLEAN DEFAULT FALSE,
  CONSTRAINT PK_PUBLISHED_BATCH PRIMARY KEY (BATCH_ID)
)
COMMENT = 'Only these batches are exposed through reporting views';

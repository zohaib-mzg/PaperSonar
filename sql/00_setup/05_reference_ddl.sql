-- =============================================================================
-- Purpose: Create reference tables for taxonomy, keyword rules, expected source
--          keys, DQ rule metadata and source precedence.
-- Inputs: PAPERSONAR.PROJECT_REF schema.
-- Outputs: REF_CATEGORY, REF_CATEGORY_KEYWORD, REF_TAXONOMY_MAP,
--          CATEGORY_OVERRIDE, REF_EXPECTED_KEY, REF_DQ_RULE, REF_SOURCE.
-- Idempotent: Yes - CREATE TABLE IF NOT EXISTS only.
-- Owner: PAPERSONAR_ADMIN
-- Parameters: None.
-- Cost: Metadata only.
-- =============================================================================

CREATE TABLE IF NOT EXISTS PAPERSONAR.PROJECT_REF.REF_CATEGORY (
  CATEGORY_KEY       VARCHAR(80)  NOT NULL,
  LABEL              VARCHAR(200) NOT NULL,
  PARENT_KEY         VARCHAR(80),
  DESCRIPTION        VARCHAR(1000),
  IS_ACTIVE          BOOLEAN DEFAULT TRUE,
  TAXONOMY_VERSION   VARCHAR(20) DEFAULT 'v1',
  CONSTRAINT PK_REF_CATEGORY PRIMARY KEY (CATEGORY_KEY)
)
COMMENT = 'Versioned internal category taxonomy';

CREATE TABLE IF NOT EXISTS PAPERSONAR.PROJECT_REF.REF_CATEGORY_KEYWORD (
  RULE_ID            VARCHAR(80)  NOT NULL,
  CATEGORY_KEY       VARCHAR(80)  NOT NULL,
  PATTERN            VARCHAR(300) NOT NULL,
  FIELD_NAME         VARCHAR(20)  NOT NULL,  -- title/keywords/abstract
  BASE_WEIGHT        NUMBER(5,2)  DEFAULT 1,
  NEGATIVE_GUARD     VARCHAR(200),
  IS_ACTIVE          BOOLEAN DEFAULT TRUE,
  RULE_VERSION       VARCHAR(20)  DEFAULT 'v1',
  CONSTRAINT PK_REF_CATEGORY_KEYWORD PRIMARY KEY (RULE_ID)
)
COMMENT = 'Weighted keyword/phrase rules; abstract weight is unused until reconstructed';

CREATE TABLE IF NOT EXISTS PAPERSONAR.PROJECT_REF.REF_TAXONOMY_MAP (
  SOURCE_NAME        VARCHAR(50)  NOT NULL,
  SOURCE_VALUE       VARCHAR(300) NOT NULL,
  CATEGORY_KEY       VARCHAR(80)  NOT NULL,
  MAPPING_VERSION    VARCHAR(20)  DEFAULT 'v1',
  IS_ACTIVE          BOOLEAN DEFAULT TRUE,
  CONSTRAINT PK_REF_TAXONOMY_MAP PRIMARY KEY (SOURCE_NAME, SOURCE_VALUE)
)
COMMENT = 'Source-provided taxonomy mapped to an internal category';

CREATE TABLE IF NOT EXISTS PAPERSONAR.PROJECT_REF.CATEGORY_OVERRIDE (
  OVERRIDE_ID        VARCHAR(100) NOT NULL,
  OUTPUT_BK          VARCHAR(300) NOT NULL,
  CATEGORY_KEY       VARCHAR(80)  NOT NULL,
  OVERRIDE_REASON    VARCHAR(1000),
  REVIEWER           VARCHAR(200),
  CREATED_AT         TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  IS_ACTIVE          BOOLEAN DEFAULT TRUE,
  CONSTRAINT PK_CATEGORY_OVERRIDE PRIMARY KEY (OVERRIDE_ID)
)
COMMENT = 'Auditable manual category overrides';

CREATE TABLE IF NOT EXISTS PAPERSONAR.PROJECT_REF.REF_EXPECTED_KEY (
  SOURCE_NAME        VARCHAR(50)  NOT NULL,
  ENTITY_NAME        VARCHAR(50)  NOT NULL,
  KEY_NAME           VARCHAR(200) NOT NULL,
  IS_REQUIRED        BOOLEAN DEFAULT FALSE,
  SCHEMA_VERSION     VARCHAR(20)  DEFAULT 'v1',
  CONSTRAINT PK_REF_EXPECTED_KEY PRIMARY KEY (SOURCE_NAME, ENTITY_NAME, KEY_NAME)
)
COMMENT = 'Explicit expected top-level payload keys; no schema inference';

CREATE TABLE IF NOT EXISTS PAPERSONAR.PROJECT_REF.REF_DQ_RULE (
  RULE_ID            VARCHAR(20)  NOT NULL,
  DESCRIPTION        VARCHAR(1000) NOT NULL,
  SEVERITY           VARCHAR(10)  NOT NULL,  -- CRITICAL/WARNING/INFO
  THRESHOLD_VALUE    NUMBER(38,6),
  IS_ACTIVE          BOOLEAN DEFAULT TRUE,
  RULE_VERSION       VARCHAR(20)  DEFAULT 'v1',
  CONSTRAINT PK_REF_DQ_RULE PRIMARY KEY (RULE_ID)
)
COMMENT = 'DQ rule inventory; thresholds are interpreted by the DQ procedure';

CREATE TABLE IF NOT EXISTS PAPERSONAR.PROJECT_REF.REF_SOURCE (
  SOURCE_NAME        VARCHAR(50)  NOT NULL,
  ENTITY_NAME        VARCHAR(50)  NOT NULL,
  SOURCE_PRIORITY    NUMBER(38,0) NOT NULL,
  IS_ACTIVE          BOOLEAN DEFAULT TRUE,
  CONSTRAINT PK_REF_SOURCE PRIMARY KEY (SOURCE_NAME, ENTITY_NAME)
)
COMMENT = 'Documented attribute survivorship priority (1 = highest)';

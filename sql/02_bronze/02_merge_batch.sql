-- =============================================================================
-- Purpose: Upsert the active batch's staging rows into bronze, keeping one
--          current row per source record id, and quarantine rows with a missing
--          required identifier.
-- Inputs: five STG_* tables, BATCH, BATCH_MANIFEST, CURRENT_BATCH.
-- Outputs: rows in the five BRZ_* tables, QUARANTINE_RECORD entries.
-- Idempotent: Yes - MERGE on (source, entity, source record id); re-fetched
--             works update the existing row instead of appending a duplicate.
-- Owner: PAPERSONAR_TRANSFORMER
-- Parameters: None - the active batch comes from CURRENT_BATCH.
-- Cost: One scan per staging table; XS warehouse compute.
-- =============================================================================
-- VERIFY: confirm SHA2(TO_JSON(variant)) is stable for the same staged file in
-- the target account. The same file always parses to the same VARIANT, so the
-- hash is deterministic for replay even though it is not a canonical JSON hash
-- across different serialisations.

CREATE OR REPLACE PROCEDURE PAPERSONAR.PROJECT_BRONZE.SP_MERGE_BATCH()
RETURNS VARCHAR
LANGUAGE SQL
AS
$$
DECLARE
  batch_id VARCHAR DEFAULT NULL;
BEGIN
  SELECT BATCH_ID INTO :batch_id
  FROM PAPERSONAR.PROJECT_AUDIT.CURRENT_BATCH
  LIMIT 1;

  IF (batch_id IS NULL) THEN
    RETURN 'NO_BATCH';
  END IF;

  -- OpenAlex -----------------------------------------------------------------
  MERGE INTO PAPERSONAR.PROJECT_BRONZE.BRZ_OPENALEX_WORK t
  USING (
    SELECT
      'OPENALEX' AS SOURCE_NAME,
      'WORK' AS ENTITY_NAME,
      REGEXP_REPLACE(s.PAYLOAD:id::STRING, '^https?://openalex[.]org/', '') AS SOURCE_RECORD_ID,
      s.BATCH_ID,
      b.WINDOW_START,
      b.WINDOW_END,
      SHA2(TO_JSON(s.PAYLOAD), 256) AS RECORD_HASH,
      m.CHECKSUM,
      s.FILE_NAME,
      s.PAYLOAD
    FROM PAPERSONAR.PROJECT_STAGING.STG_OPENALEX_WORK s
    JOIN PAPERSONAR.PROJECT_AUDIT.BATCH b ON b.BATCH_ID = s.BATCH_ID
    LEFT JOIN PAPERSONAR.PROJECT_AUDIT.BATCH_MANIFEST m
      ON m.BATCH_ID = s.BATCH_ID AND m.FILE_NAME = s.FILE_NAME
    WHERE s.BATCH_ID = :batch_id
      AND COALESCE(s.PAYLOAD:id::STRING, '') <> ''
    QUALIFY ROW_NUMBER() OVER (
      PARTITION BY REGEXP_REPLACE(s.PAYLOAD:id::STRING, '^https?://openalex[.]org/', '')
      ORDER BY s.FILE_NAME DESC, s.FILE_ROW_NUMBER DESC
    ) = 1
  ) s
  ON t.SOURCE_NAME = s.SOURCE_NAME
 AND t.ENTITY_NAME = s.ENTITY_NAME
 AND t.SOURCE_RECORD_ID = s.SOURCE_RECORD_ID
  WHEN MATCHED THEN UPDATE SET
    t.BATCH_ID = s.BATCH_ID,
    t.WINDOW_START = s.WINDOW_START,
    t.WINDOW_END = s.WINDOW_END,
    t.RECORD_HASH = s.RECORD_HASH,
    t.CHECKSUM = s.CHECKSUM,
    t.FILE_NAME = s.FILE_NAME,
    t.PAYLOAD = s.PAYLOAD,
    t.INGESTED_AT = CURRENT_TIMESTAMP()
  WHEN NOT MATCHED THEN INSERT
    (SOURCE_NAME, ENTITY_NAME, SOURCE_RECORD_ID, BATCH_ID, WINDOW_START,
     WINDOW_END, RECORD_HASH, CHECKSUM, FILE_NAME, PAYLOAD, INGESTED_AT)
    VALUES (s.SOURCE_NAME, s.ENTITY_NAME, s.SOURCE_RECORD_ID, s.BATCH_ID,
            s.WINDOW_START, s.WINDOW_END, s.RECORD_HASH, s.CHECKSUM,
            s.FILE_NAME, s.PAYLOAD, CURRENT_TIMESTAMP());

  MERGE INTO PAPERSONAR.PROJECT_AUDIT.QUARANTINE_RECORD t
  USING (
    SELECT
      SHA2('OPENALEX|' || COALESCE(s.BATCH_ID, '') || '|' || COALESCE(s.FILE_NAME, '') || '|' ||
           COALESCE(s.FILE_ROW_NUMBER::STRING, '') || '|MISSING_REQUIRED_ID', 256) AS QUARANTINE_ID,
      s.BATCH_ID, 'OPENALEX' AS SOURCE_NAME, 'WORK' AS ENTITY_NAME,
      SHA2(TO_JSON(s.PAYLOAD), 256) AS RECORD_HASH,
      OBJECT_CONSTRUCT('file_name', s.FILE_NAME, 'file_row_number', s.FILE_ROW_NUMBER) AS DETAIL,
      s.FILE_NAME
    FROM PAPERSONAR.PROJECT_STAGING.STG_OPENALEX_WORK s
    WHERE s.BATCH_ID = :batch_id AND COALESCE(s.PAYLOAD:id::STRING, '') = ''
  ) s
  ON t.QUARANTINE_ID = s.QUARANTINE_ID
  WHEN NOT MATCHED THEN INSERT
    (QUARANTINE_ID, BATCH_ID, SOURCE_NAME, ENTITY_NAME, SOURCE_RECORD_ID,
     RECORD_HASH, REASON_CODE, DETAIL, RAW_REFERENCE)
    VALUES (s.QUARANTINE_ID, s.BATCH_ID, s.SOURCE_NAME, s.ENTITY_NAME, NULL,
            s.RECORD_HASH, 'MISSING_REQUIRED_ID', s.DETAIL, s.FILE_NAME);

  -- Crossref -----------------------------------------------------------------
  MERGE INTO PAPERSONAR.PROJECT_BRONZE.BRZ_CROSSREF_WORK t
  USING (
    SELECT
      'CROSSREF' AS SOURCE_NAME,
      'WORK' AS ENTITY_NAME,
      COALESCE(s.PAYLOAD:DOI::STRING, s.PAYLOAD:URL::STRING) AS SOURCE_RECORD_ID,
      s.BATCH_ID,
      b.WINDOW_START,
      b.WINDOW_END,
      SHA2(TO_JSON(s.PAYLOAD), 256) AS RECORD_HASH,
      m.CHECKSUM,
      s.FILE_NAME,
      s.PAYLOAD
    FROM PAPERSONAR.PROJECT_STAGING.STG_CROSSREF_WORK s
    JOIN PAPERSONAR.PROJECT_AUDIT.BATCH b ON b.BATCH_ID = s.BATCH_ID
    LEFT JOIN PAPERSONAR.PROJECT_AUDIT.BATCH_MANIFEST m
      ON m.BATCH_ID = s.BATCH_ID AND m.FILE_NAME = s.FILE_NAME
    WHERE s.BATCH_ID = :batch_id
      AND COALESCE(s.PAYLOAD:DOI::STRING, s.PAYLOAD:URL::STRING, '') <> ''
    QUALIFY ROW_NUMBER() OVER (
      PARTITION BY COALESCE(s.PAYLOAD:DOI::STRING, s.PAYLOAD:URL::STRING)
      ORDER BY s.FILE_NAME DESC, s.FILE_ROW_NUMBER DESC
    ) = 1
  ) s
  ON t.SOURCE_NAME = s.SOURCE_NAME
 AND t.ENTITY_NAME = s.ENTITY_NAME
 AND t.SOURCE_RECORD_ID = s.SOURCE_RECORD_ID
  WHEN MATCHED THEN UPDATE SET
    t.BATCH_ID = s.BATCH_ID,
    t.WINDOW_START = s.WINDOW_START,
    t.WINDOW_END = s.WINDOW_END,
    t.RECORD_HASH = s.RECORD_HASH,
    t.CHECKSUM = s.CHECKSUM,
    t.FILE_NAME = s.FILE_NAME,
    t.PAYLOAD = s.PAYLOAD,
    t.INGESTED_AT = CURRENT_TIMESTAMP()
  WHEN NOT MATCHED THEN INSERT
    (SOURCE_NAME, ENTITY_NAME, SOURCE_RECORD_ID, BATCH_ID, WINDOW_START,
     WINDOW_END, RECORD_HASH, CHECKSUM, FILE_NAME, PAYLOAD, INGESTED_AT)
    VALUES (s.SOURCE_NAME, s.ENTITY_NAME, s.SOURCE_RECORD_ID, s.BATCH_ID,
            s.WINDOW_START, s.WINDOW_END, s.RECORD_HASH, s.CHECKSUM,
            s.FILE_NAME, s.PAYLOAD, CURRENT_TIMESTAMP());

  MERGE INTO PAPERSONAR.PROJECT_AUDIT.QUARANTINE_RECORD t
  USING (
    SELECT
      SHA2('CROSSREF|' || COALESCE(s.BATCH_ID, '') || '|' || COALESCE(s.FILE_NAME, '') || '|' ||
           COALESCE(s.FILE_ROW_NUMBER::STRING, '') || '|MISSING_REQUIRED_ID', 256) AS QUARANTINE_ID,
      s.BATCH_ID, 'CROSSREF' AS SOURCE_NAME, 'WORK' AS ENTITY_NAME,
      SHA2(TO_JSON(s.PAYLOAD), 256) AS RECORD_HASH,
      OBJECT_CONSTRUCT('file_name', s.FILE_NAME, 'file_row_number', s.FILE_ROW_NUMBER) AS DETAIL,
      s.FILE_NAME
    FROM PAPERSONAR.PROJECT_STAGING.STG_CROSSREF_WORK s
    WHERE s.BATCH_ID = :batch_id
      AND COALESCE(s.PAYLOAD:DOI::STRING, s.PAYLOAD:URL::STRING, '') = ''
  ) s
  ON t.QUARANTINE_ID = s.QUARANTINE_ID
  WHEN NOT MATCHED THEN INSERT
    (QUARANTINE_ID, BATCH_ID, SOURCE_NAME, ENTITY_NAME, SOURCE_RECORD_ID,
     RECORD_HASH, REASON_CODE, DETAIL, RAW_REFERENCE)
    VALUES (s.QUARANTINE_ID, s.BATCH_ID, s.SOURCE_NAME, s.ENTITY_NAME, NULL,
            s.RECORD_HASH, 'MISSING_REQUIRED_ID', s.DETAIL, s.FILE_NAME);

  -- arXiv --------------------------------------------------------------------
  MERGE INTO PAPERSONAR.PROJECT_BRONZE.BRZ_ARXIV_RECORD t
  USING (
    SELECT
      'ARXIV' AS SOURCE_NAME,
      'RECORD' AS ENTITY_NAME,
      s.PAYLOAD:identifier::STRING AS SOURCE_RECORD_ID,
      s.BATCH_ID,
      b.WINDOW_START,
      b.WINDOW_END,
      SHA2(TO_JSON(s.PAYLOAD), 256) AS RECORD_HASH,
      m.CHECKSUM,
      s.FILE_NAME,
      s.PAYLOAD
    FROM PAPERSONAR.PROJECT_STAGING.STG_ARXIV_RECORD s
    JOIN PAPERSONAR.PROJECT_AUDIT.BATCH b ON b.BATCH_ID = s.BATCH_ID
    LEFT JOIN PAPERSONAR.PROJECT_AUDIT.BATCH_MANIFEST m
      ON m.BATCH_ID = s.BATCH_ID AND m.FILE_NAME = s.FILE_NAME
    WHERE s.BATCH_ID = :batch_id
      AND COALESCE(s.PAYLOAD:identifier::STRING, '') <> ''
    QUALIFY ROW_NUMBER() OVER (
      PARTITION BY s.PAYLOAD:identifier::STRING
      ORDER BY s.FILE_NAME DESC, s.FILE_ROW_NUMBER DESC
    ) = 1
  ) s
  ON t.SOURCE_NAME = s.SOURCE_NAME
 AND t.ENTITY_NAME = s.ENTITY_NAME
 AND t.SOURCE_RECORD_ID = s.SOURCE_RECORD_ID
  WHEN MATCHED THEN UPDATE SET
    t.BATCH_ID = s.BATCH_ID,
    t.WINDOW_START = s.WINDOW_START,
    t.WINDOW_END = s.WINDOW_END,
    t.RECORD_HASH = s.RECORD_HASH,
    t.CHECKSUM = s.CHECKSUM,
    t.FILE_NAME = s.FILE_NAME,
    t.PAYLOAD = s.PAYLOAD,
    t.INGESTED_AT = CURRENT_TIMESTAMP()
  WHEN NOT MATCHED THEN INSERT
    (SOURCE_NAME, ENTITY_NAME, SOURCE_RECORD_ID, BATCH_ID, WINDOW_START,
     WINDOW_END, RECORD_HASH, CHECKSUM, FILE_NAME, PAYLOAD, INGESTED_AT)
    VALUES (s.SOURCE_NAME, s.ENTITY_NAME, s.SOURCE_RECORD_ID, s.BATCH_ID,
            s.WINDOW_START, s.WINDOW_END, s.RECORD_HASH, s.CHECKSUM,
            s.FILE_NAME, s.PAYLOAD, CURRENT_TIMESTAMP());

  MERGE INTO PAPERSONAR.PROJECT_AUDIT.QUARANTINE_RECORD t
  USING (
    SELECT
      SHA2('ARXIV|' || COALESCE(s.BATCH_ID, '') || '|' || COALESCE(s.FILE_NAME, '') || '|' ||
           COALESCE(s.FILE_ROW_NUMBER::STRING, '') || '|MISSING_REQUIRED_ID', 256) AS QUARANTINE_ID,
      s.BATCH_ID, 'ARXIV' AS SOURCE_NAME, 'RECORD' AS ENTITY_NAME,
      SHA2(TO_JSON(s.PAYLOAD), 256) AS RECORD_HASH,
      OBJECT_CONSTRUCT('file_name', s.FILE_NAME, 'file_row_number', s.FILE_ROW_NUMBER) AS DETAIL,
      s.FILE_NAME
    FROM PAPERSONAR.PROJECT_STAGING.STG_ARXIV_RECORD s
    WHERE s.BATCH_ID = :batch_id AND COALESCE(s.PAYLOAD:identifier::STRING, '') = ''
  ) s
  ON t.QUARANTINE_ID = s.QUARANTINE_ID
  WHEN NOT MATCHED THEN INSERT
    (QUARANTINE_ID, BATCH_ID, SOURCE_NAME, ENTITY_NAME, SOURCE_RECORD_ID,
     RECORD_HASH, REASON_CODE, DETAIL, RAW_REFERENCE)
    VALUES (s.QUARANTINE_ID, s.BATCH_ID, s.SOURCE_NAME, s.ENTITY_NAME, NULL,
            s.RECORD_HASH, 'MISSING_REQUIRED_ID', s.DETAIL, s.FILE_NAME);

  -- DataCite -----------------------------------------------------------------
  MERGE INTO PAPERSONAR.PROJECT_BRONZE.BRZ_DATACITE_DOI t
  USING (
    SELECT
      'DATACITE' AS SOURCE_NAME,
      'DOI' AS ENTITY_NAME,
      COALESCE(s.PAYLOAD:attributes.doi::STRING, s.PAYLOAD:id::STRING) AS SOURCE_RECORD_ID,
      s.BATCH_ID,
      b.WINDOW_START,
      b.WINDOW_END,
      SHA2(TO_JSON(s.PAYLOAD), 256) AS RECORD_HASH,
      m.CHECKSUM,
      s.FILE_NAME,
      s.PAYLOAD
    FROM PAPERSONAR.PROJECT_STAGING.STG_DATACITE_DOI s
    JOIN PAPERSONAR.PROJECT_AUDIT.BATCH b ON b.BATCH_ID = s.BATCH_ID
    LEFT JOIN PAPERSONAR.PROJECT_AUDIT.BATCH_MANIFEST m
      ON m.BATCH_ID = s.BATCH_ID AND m.FILE_NAME = s.FILE_NAME
    WHERE s.BATCH_ID = :batch_id
      AND COALESCE(s.PAYLOAD:attributes.doi::STRING, s.PAYLOAD:id::STRING, '') <> ''
    QUALIFY ROW_NUMBER() OVER (
      PARTITION BY COALESCE(s.PAYLOAD:attributes.doi::STRING, s.PAYLOAD:id::STRING)
      ORDER BY s.FILE_NAME DESC, s.FILE_ROW_NUMBER DESC
    ) = 1
  ) s
  ON t.SOURCE_NAME = s.SOURCE_NAME
 AND t.ENTITY_NAME = s.ENTITY_NAME
 AND t.SOURCE_RECORD_ID = s.SOURCE_RECORD_ID
  WHEN MATCHED THEN UPDATE SET
    t.BATCH_ID = s.BATCH_ID,
    t.WINDOW_START = s.WINDOW_START,
    t.WINDOW_END = s.WINDOW_END,
    t.RECORD_HASH = s.RECORD_HASH,
    t.CHECKSUM = s.CHECKSUM,
    t.FILE_NAME = s.FILE_NAME,
    t.PAYLOAD = s.PAYLOAD,
    t.INGESTED_AT = CURRENT_TIMESTAMP()
  WHEN NOT MATCHED THEN INSERT
    (SOURCE_NAME, ENTITY_NAME, SOURCE_RECORD_ID, BATCH_ID, WINDOW_START,
     WINDOW_END, RECORD_HASH, CHECKSUM, FILE_NAME, PAYLOAD, INGESTED_AT)
    VALUES (s.SOURCE_NAME, s.ENTITY_NAME, s.SOURCE_RECORD_ID, s.BATCH_ID,
            s.WINDOW_START, s.WINDOW_END, s.RECORD_HASH, s.CHECKSUM,
            s.FILE_NAME, s.PAYLOAD, CURRENT_TIMESTAMP());

  MERGE INTO PAPERSONAR.PROJECT_AUDIT.QUARANTINE_RECORD t
  USING (
    SELECT
      SHA2('DATACITE|' || COALESCE(s.BATCH_ID, '') || '|' || COALESCE(s.FILE_NAME, '') || '|' ||
           COALESCE(s.FILE_ROW_NUMBER::STRING, '') || '|MISSING_REQUIRED_ID', 256) AS QUARANTINE_ID,
      s.BATCH_ID, 'DATACITE' AS SOURCE_NAME, 'DOI' AS ENTITY_NAME,
      SHA2(TO_JSON(s.PAYLOAD), 256) AS RECORD_HASH,
      OBJECT_CONSTRUCT('file_name', s.FILE_NAME, 'file_row_number', s.FILE_ROW_NUMBER) AS DETAIL,
      s.FILE_NAME
    FROM PAPERSONAR.PROJECT_STAGING.STG_DATACITE_DOI s
    WHERE s.BATCH_ID = :batch_id
      AND COALESCE(s.PAYLOAD:attributes.doi::STRING, s.PAYLOAD:id::STRING, '') = ''
  ) s
  ON t.QUARANTINE_ID = s.QUARANTINE_ID
  WHEN NOT MATCHED THEN INSERT
    (QUARANTINE_ID, BATCH_ID, SOURCE_NAME, ENTITY_NAME, SOURCE_RECORD_ID,
     RECORD_HASH, REASON_CODE, DETAIL, RAW_REFERENCE)
    VALUES (s.QUARANTINE_ID, s.BATCH_ID, s.SOURCE_NAME, s.ENTITY_NAME, NULL,
            s.RECORD_HASH, 'MISSING_REQUIRED_ID', s.DETAIL, s.FILE_NAME);

  -- Zenodo -------------------------------------------------------------------
  MERGE INTO PAPERSONAR.PROJECT_BRONZE.BRZ_ZENODO_RECORD t
  USING (
    SELECT
      'ZENODO' AS SOURCE_NAME,
      'RECORD' AS ENTITY_NAME,
      s.PAYLOAD:identifier::STRING AS SOURCE_RECORD_ID,
      s.BATCH_ID,
      b.WINDOW_START,
      b.WINDOW_END,
      SHA2(TO_JSON(s.PAYLOAD), 256) AS RECORD_HASH,
      m.CHECKSUM,
      s.FILE_NAME,
      s.PAYLOAD
    FROM PAPERSONAR.PROJECT_STAGING.STG_ZENODO_RECORD s
    JOIN PAPERSONAR.PROJECT_AUDIT.BATCH b ON b.BATCH_ID = s.BATCH_ID
    LEFT JOIN PAPERSONAR.PROJECT_AUDIT.BATCH_MANIFEST m
      ON m.BATCH_ID = s.BATCH_ID AND m.FILE_NAME = s.FILE_NAME
    WHERE s.BATCH_ID = :batch_id
      AND COALESCE(s.PAYLOAD:identifier::STRING, '') <> ''
    QUALIFY ROW_NUMBER() OVER (
      PARTITION BY s.PAYLOAD:identifier::STRING
      ORDER BY s.FILE_NAME DESC, s.FILE_ROW_NUMBER DESC
    ) = 1
  ) s
  ON t.SOURCE_NAME = s.SOURCE_NAME
 AND t.ENTITY_NAME = s.ENTITY_NAME
 AND t.SOURCE_RECORD_ID = s.SOURCE_RECORD_ID
  WHEN MATCHED THEN UPDATE SET
    t.BATCH_ID = s.BATCH_ID,
    t.WINDOW_START = s.WINDOW_START,
    t.WINDOW_END = s.WINDOW_END,
    t.RECORD_HASH = s.RECORD_HASH,
    t.CHECKSUM = s.CHECKSUM,
    t.FILE_NAME = s.FILE_NAME,
    t.PAYLOAD = s.PAYLOAD,
    t.INGESTED_AT = CURRENT_TIMESTAMP()
  WHEN NOT MATCHED THEN INSERT
    (SOURCE_NAME, ENTITY_NAME, SOURCE_RECORD_ID, BATCH_ID, WINDOW_START,
     WINDOW_END, RECORD_HASH, CHECKSUM, FILE_NAME, PAYLOAD, INGESTED_AT)
    VALUES (s.SOURCE_NAME, s.ENTITY_NAME, s.SOURCE_RECORD_ID, s.BATCH_ID,
            s.WINDOW_START, s.WINDOW_END, s.RECORD_HASH, s.CHECKSUM,
            s.FILE_NAME, s.PAYLOAD, CURRENT_TIMESTAMP());

  MERGE INTO PAPERSONAR.PROJECT_AUDIT.QUARANTINE_RECORD t
  USING (
    SELECT
      SHA2('ZENODO|' || COALESCE(s.BATCH_ID, '') || '|' || COALESCE(s.FILE_NAME, '') || '|' ||
           COALESCE(s.FILE_ROW_NUMBER::STRING, '') || '|MISSING_REQUIRED_ID', 256) AS QUARANTINE_ID,
      s.BATCH_ID, 'ZENODO' AS SOURCE_NAME, 'RECORD' AS ENTITY_NAME,
      SHA2(TO_JSON(s.PAYLOAD), 256) AS RECORD_HASH,
      OBJECT_CONSTRUCT('file_name', s.FILE_NAME, 'file_row_number', s.FILE_ROW_NUMBER) AS DETAIL,
      s.FILE_NAME
    FROM PAPERSONAR.PROJECT_STAGING.STG_ZENODO_RECORD s
    WHERE s.BATCH_ID = :batch_id AND COALESCE(s.PAYLOAD:identifier::STRING, '') = ''
  ) s
  ON t.QUARANTINE_ID = s.QUARANTINE_ID
  WHEN NOT MATCHED THEN INSERT
    (QUARANTINE_ID, BATCH_ID, SOURCE_NAME, ENTITY_NAME, SOURCE_RECORD_ID,
     RECORD_HASH, REASON_CODE, DETAIL, RAW_REFERENCE)
    VALUES (s.QUARANTINE_ID, s.BATCH_ID, s.SOURCE_NAME, s.ENTITY_NAME, NULL,
            s.RECORD_HASH, 'MISSING_REQUIRED_ID', s.DETAIL, s.FILE_NAME);

  RETURN 'MERGED';
END;
$$;

COMMENT ON PROCEDURE PAPERSONAR.PROJECT_BRONZE.SP_MERGE_BATCH()

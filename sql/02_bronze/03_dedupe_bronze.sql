-- =============================================================================
-- Purpose: One-time compaction of legacy append-only bronze duplicates to one
--          current row per (source, entity, source record id).
-- Inputs: five BRZ_* tables.
-- Outputs: duplicate historical observations removed; the latest observation
--          per record id is retained; table comments updated.
-- Idempotent: Yes - a second run finds no RN > 1 rows and rewrites no rows.
-- Owner: PAPERSONAR_ADMIN
-- Parameters: None.
-- Cost: One scan and one rewrite per bronze table. Run once during a
--       maintenance window with no extraction or task graph running.
-- =============================================================================
-- This file is a maintenance migration, not part of the daily task graph.
-- It keeps the table objects (and therefore grants/defaults) intact by
-- deleting and re-inserting rows. A crash between the DELETE and INSERT can
-- leave an empty table; re-run this file after recovering the source batches
-- or restore from Time Travel if needed.

CREATE OR REPLACE TEMPORARY TABLE TMP_BRZ_OPENALEX_WORK AS
SELECT * FROM PAPERSONAR.PROJECT_BRONZE.BRZ_OPENALEX_WORK
QUALIFY ROW_NUMBER() OVER (
  PARTITION BY SOURCE_NAME, ENTITY_NAME, SOURCE_RECORD_ID
  ORDER BY INGESTED_AT DESC NULLS LAST, BATCH_ID DESC, RECORD_HASH DESC
) = 1;
DELETE FROM PAPERSONAR.PROJECT_BRONZE.BRZ_OPENALEX_WORK;
INSERT INTO PAPERSONAR.PROJECT_BRONZE.BRZ_OPENALEX_WORK
SELECT * FROM TMP_BRZ_OPENALEX_WORK;
COMMENT ON TABLE PAPERSONAR.PROJECT_BRONZE.BRZ_OPENALEX_WORK
  IS 'Current-state OpenAlex work observations, one row per work id';


-- =============================================================================
-- Purpose: Create the silver observation, identity crosswalk and canonical
--          research-output tables.
-- Inputs: PROJECT_SILVER schema.
-- Outputs: SLV_SOURCE_OBSERVATION, SLV_OUTPUT_CROSSWALK, SLV_RESEARCH_OUTPUT.
-- Idempotent: Yes - CREATE TABLE IF NOT EXISTS only.
-- Owner: PAPERSONAR_ADMIN
-- Parameters: None.
-- Cost: Metadata only.
-- =============================================================================

CREATE TABLE IF NOT EXISTS PAPERSONAR.PROJECT_SILVER.SLV_SOURCE_OBSERVATION (
  OBSERVATION_ID        VARCHAR(64)   NOT NULL,
  SOURCE_NAME           VARCHAR(50)   NOT NULL,
  ENTITY_NAME           VARCHAR(50)   NOT NULL,
  SOURCE_RECORD_ID      VARCHAR(1000) NOT NULL,
  RECORD_HASH           VARCHAR(64)   NOT NULL,
  BATCH_ID              VARCHAR(64)   NOT NULL,
  DOI_RAW               VARCHAR(1000),
  DOI_NORMALIZED        VARCHAR(1000),
  IS_DOI_VALID          BOOLEAN,
  ARXIV_ID              VARCHAR(200),
  TITLE_RAW             VARCHAR(16000),
  TITLE_NORMALIZED      VARCHAR(16000),
  PUBLICATION_DATE_RAW  VARCHAR(4000),
  PUBLICATION_DATE      DATE,
  PUBLICATION_YEAR      NUMBER(38,0),
  OUTPUT_TYPE           VARCHAR(100),
  VENUE_NAME            VARCHAR(1000),
  OA_IS_OA              BOOLEAN,
  OA_STATUS             VARCHAR(50),
  CITED_BY_COUNT        NUMBER(38,0),
  FIRST_AUTHOR_NAME     VARCHAR(500),
  FIRST_AUTHOR_ID       VARCHAR(500),
  TOPICS                VARIANT,
  AUTHORS               VARIANT,
  REFERENCES_JSON       VARIANT,
  LANGUAGE              VARCHAR(20),
  SOURCE_UPDATED_AT     TIMESTAMP_NTZ,
  PROVENANCE            VARIANT,
  INGESTED_AT           TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  CONSTRAINT PK_SLV_SOURCE_OBSERVATION
    PRIMARY KEY (BATCH_ID, SOURCE_NAME, ENTITY_NAME, SOURCE_RECORD_ID, RECORD_HASH)
)
COMMENT = 'Typed projection of one bronze observation; raw payload remains in bronze';

CREATE TABLE IF NOT EXISTS PAPERSONAR.PROJECT_SILVER.SLV_OUTPUT_CROSSWALK (
  SOURCE_NAME       VARCHAR(50)   NOT NULL,
  ENTITY_NAME       VARCHAR(50)   NOT NULL,
  SOURCE_RECORD_ID  VARCHAR(1000) NOT NULL,
  RECORD_HASH       VARCHAR(64)   NOT NULL,
  OUTPUT_BK         VARCHAR(300)  NOT NULL,
  MATCH_METHOD      VARCHAR(30)   NOT NULL,  -- DOI/ARXIV/TITLE_AUTHOR_YEAR
  CONFIDENCE        NUMBER(5,4)   NOT NULL,
  RULE_VERSION      VARCHAR(20)   NOT NULL,
  BATCH_ID          VARCHAR(64)   NOT NULL,
  CREATED_AT        TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  CONSTRAINT PK_SLV_OUTPUT_CROSSWALK
    PRIMARY KEY (BATCH_ID, SOURCE_NAME, ENTITY_NAME, SOURCE_RECORD_ID, RECORD_HASH)
)
COMMENT = 'Auditable mapping from source observation to canonical output business key';

CREATE TABLE IF NOT EXISTS PAPERSONAR.PROJECT_SILVER.SLV_RESEARCH_OUTPUT (
  OUTPUT_BK           VARCHAR(300)  NOT NULL,
  DOI_NORMALIZED      VARCHAR(1000),
  TITLE               VARCHAR(16000),
  PUBLICATION_DATE    DATE,
  PUBLICATION_YEAR    NUMBER(38,0),
  OUTPUT_TYPE         VARCHAR(100),
  VENUE_NAME          VARCHAR(1000),
  OA_IS_OA            BOOLEAN,
  OA_STATUS           VARCHAR(50),
  CITED_BY_COUNT      NUMBER(38,0),
  LANGUAGE            VARCHAR(20),
  PRIMARY_SOURCE_NAME VARCHAR(50),
  FIRST_SEEN_AT       TIMESTAMP_NTZ,
  LAST_SEEN_AT        TIMESTAMP_NTZ,
  LAST_BATCH_ID       VARCHAR(64),
  CONSTRAINT PK_SLV_RESEARCH_OUTPUT PRIMARY KEY (OUTPUT_BK)
)
COMMENT = 'Canonical research output with documented source-precedence survivorship';

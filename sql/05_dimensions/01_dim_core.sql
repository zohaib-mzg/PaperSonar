-- =============================================================================
-- Purpose: Create the conformed-dimension key map, date dimension and the core
--          Type 1 dimensions used by every fact.
-- Inputs: PROJECT_DW schema.
-- Outputs: DIMENSION_KEY_MAP, SP_ENSURE_KEYS, DIM_DATE, DIM_SOURCE,
--          DIM_OUTPUT_TYPE, DIM_VENUE, DIM_ACCESS_STATUS, DIM_LANGUAGE,
--          DIM_COUNTRY.
-- Idempotent: Yes - CREATE ... IF NOT EXISTS; seed logic is MERGE/anti-join.
-- Owner: PAPERSONAR_ADMIN
-- Parameters: None.
-- Cost: DIM_DATE is a one-time 40-year static load (about 14.6k rows).
-- =============================================================================
-- Every dimension has a numeric surrogate key and a business key. Unknown
-- members use surrogate key 0 (date) or the mapped '-1' business key. The date
-- dimension intentionally uses the conventional YYYYMMDD smart key as its
-- documented surrogate; all other dimensions use DIMENSION_KEY_MAP sequences.

CREATE TABLE IF NOT EXISTS PAPERSONAR.PROJECT_DW.DIMENSION_KEY_MAP (
  DIMENSION_NAME  VARCHAR(50)  NOT NULL,
  BUSINESS_KEY    VARCHAR(500) NOT NULL,
  SURROGATE_KEY   NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1,
  CREATED_AT      TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  CONSTRAINT PK_DIMENSION_KEY_MAP PRIMARY KEY (DIMENSION_NAME, BUSINESS_KEY),
  CONSTRAINT UQ_DIMENSION_KEY_MAP UNIQUE (DIMENSION_NAME, SURROGATE_KEY)
)
COMMENT = 'Stable numeric surrogate keys for business keys; gaps are acceptable';

CREATE OR REPLACE PROCEDURE PAPERSONAR.PROJECT_DW.SP_ENSURE_KEYS(
  P_DIMENSION_NAME VARCHAR,
  P_BUSINESS_KEYS ARRAY
)
RETURNS NUMBER
LANGUAGE SQL
AS
$$
DECLARE
  inserted_keys NUMBER DEFAULT 0;
BEGIN
  INSERT INTO PAPERSONAR.PROJECT_DW.DIMENSION_KEY_MAP (DIMENSION_NAME, BUSINESS_KEY)
  SELECT :P_DIMENSION_NAME, keys.value::STRING
  FROM TABLE(FLATTEN(input => :P_BUSINESS_KEYS)) keys
  WHERE keys.value IS NOT NULL
    AND TRIM(keys.value::STRING) <> ''
    AND NOT EXISTS (
      SELECT 1
      FROM PAPERSONAR.PROJECT_DW.DIMENSION_KEY_MAP existing
      WHERE existing.DIMENSION_NAME = :P_DIMENSION_NAME
        AND existing.BUSINESS_KEY = keys.value::STRING
    );
  inserted_keys := SQLROWCOUNT;
  RETURN inserted_keys;
END;
$$;

CREATE TABLE IF NOT EXISTS PAPERSONAR.PROJECT_DW.DIM_DATE (
  DATE_SK       NUMBER(38,0) NOT NULL,
  DATE_KEY      NUMBER(38,0) NOT NULL,
  FULL_DATE     DATE,
  YEAR          NUMBER(38,0),
  QUARTER       NUMBER(38,0),
  MONTH         NUMBER(38,0),
  MONTH_NAME    VARCHAR(20),
  DAY_OF_MONTH  NUMBER(38,0),
  DAY_OF_WEEK   NUMBER(38,0),
  DAY_NAME      VARCHAR(20),
  IS_WEEKEND    BOOLEAN,
  IS_UNKNOWN    BOOLEAN DEFAULT FALSE,
  CONSTRAINT PK_DIM_DATE PRIMARY KEY (DATE_SK)
)
COMMENT = 'Conformed date dimension 2000-2039 plus unknown member 0';

MERGE INTO PAPERSONAR.PROJECT_DW.DIM_DATE t
USING (
  SELECT 0 AS DATE_SK, 0 AS DATE_KEY, NULL AS FULL_DATE, NULL AS YEAR,
         NULL AS QUARTER, NULL AS MONTH, 'Unknown' AS MONTH_NAME,
         NULL AS DAY_OF_MONTH, NULL AS DAY_OF_WEEK, 'Unknown' AS DAY_NAME,
         FALSE AS IS_WEEKEND, TRUE AS IS_UNKNOWN
) s
ON t.DATE_SK = s.DATE_SK
WHEN NOT MATCHED THEN INSERT
  (DATE_SK, DATE_KEY, FULL_DATE, YEAR, QUARTER, MONTH, MONTH_NAME,
   DAY_OF_MONTH, DAY_OF_WEEK, DAY_NAME, IS_WEEKEND, IS_UNKNOWN)
  VALUES (s.DATE_SK, s.DATE_KEY, s.FULL_DATE, s.YEAR, s.QUARTER, s.MONTH,
          s.MONTH_NAME, s.DAY_OF_MONTH, s.DAY_OF_WEEK, s.DAY_NAME,
          s.IS_WEEKEND, s.IS_UNKNOWN);

INSERT INTO PAPERSONAR.PROJECT_DW.DIM_DATE (
  DATE_SK, DATE_KEY, FULL_DATE, YEAR, QUARTER, MONTH, MONTH_NAME,
  DAY_OF_MONTH, DAY_OF_WEEK, DAY_NAME, IS_WEEKEND, IS_UNKNOWN
)
SELECT
  TO_NUMBER(TO_CHAR(day_value, 'YYYYMMDD')) AS DATE_SK,
  TO_NUMBER(TO_CHAR(day_value, 'YYYYMMDD')) AS DATE_KEY,
  day_value,
  YEAR(day_value),
  QUARTER(day_value),
  MONTH(day_value),
  TO_CHAR(day_value, 'MMMM'),
  DAY(day_value),
  DAYOFWEEK(day_value),
  TO_CHAR(day_value, 'DY'),
  DAYOFWEEK(day_value) IN (0, 6),
  FALSE
FROM (
  SELECT DATEADD(day, SEQ4(), TO_DATE('2000-01-01')) AS day_value
  FROM TABLE(GENERATOR(ROWCOUNT => 14610))
) days
WHERE NOT EXISTS (
  SELECT 1
  FROM PAPERSONAR.PROJECT_DW.DIM_DATE existing
  WHERE existing.DATE_SK = TO_NUMBER(TO_CHAR(day_value, 'YYYYMMDD'))
);

CREATE TABLE IF NOT EXISTS PAPERSONAR.PROJECT_DW.DIM_SOURCE (
  SOURCE_SK       NUMBER(38,0) NOT NULL,
  SOURCE_NAME     VARCHAR(50)  NOT NULL,
  ENTITY_NAME     VARCHAR(50)  NOT NULL,
  SOURCE_PRIORITY NUMBER(38,0),
  IS_ACTIVE       BOOLEAN DEFAULT TRUE,
  IS_UNKNOWN      BOOLEAN DEFAULT FALSE,
  CONSTRAINT PK_DIM_SOURCE PRIMARY KEY (SOURCE_SK)
)
COMMENT = 'Controlled source dimension; fixed keys are documented and stable';

MERGE INTO PAPERSONAR.PROJECT_DW.DIM_SOURCE t
USING (
  SELECT column1 AS SOURCE_SK, column2 AS SOURCE_NAME, column3 AS ENTITY_NAME,
         column4 AS SOURCE_PRIORITY, column5 AS IS_UNKNOWN
  FROM VALUES
    (-1, 'UNKNOWN', 'UNKNOWN', 99, TRUE),
    (1, 'OPENALEX', 'WORK', 1, FALSE),
    (2, 'CROSSREF', 'WORK', 2, FALSE),
    (3, 'ARXIV', 'RECORD', 3, FALSE),
    (4, 'DATACITE', 'DOI', 4, FALSE),
    (5, 'ZENODO', 'RECORD', 5, FALSE)
) s
ON t.SOURCE_SK = s.SOURCE_SK
WHEN MATCHED THEN UPDATE SET
  t.SOURCE_NAME = s.SOURCE_NAME,
  t.ENTITY_NAME = s.ENTITY_NAME,
  t.SOURCE_PRIORITY = s.SOURCE_PRIORITY,
  t.IS_UNKNOWN = s.IS_UNKNOWN,
  t.IS_ACTIVE = TRUE
WHEN NOT MATCHED THEN INSERT
  (SOURCE_SK, SOURCE_NAME, ENTITY_NAME, SOURCE_PRIORITY, IS_ACTIVE, IS_UNKNOWN)
  VALUES (s.SOURCE_SK, s.SOURCE_NAME, s.ENTITY_NAME, s.SOURCE_PRIORITY, TRUE, s.IS_UNKNOWN);


-- =============================================================================
-- Purpose: Create the fact and bridge tables with explicit grains and
--          surrogate-key foreign references to conformed dimensions.
-- Inputs: PROJECT_DW schema.
-- Outputs: FACT_RESEARCH_OUTPUT, FACT_CITATION_SNAPSHOT,
--          FACT_OUTPUT_SOURCE_OBSERVATION, FACT_OUTPUT_RELATION,
--          BRIDGE_OUTPUT_AUTHOR, BRIDGE_OUTPUT_TOPIC_CATEGORY,
--          BRIDGE_AUTHOR_INSTITUTION.
-- Idempotent: Yes - CREATE TABLE IF NOT EXISTS only.
-- Owner: PAPERSONAR_ADMIN
-- Parameters: None.
-- Cost: Metadata only.
-- =============================================================================
-- Grains:
--   FACT_RESEARCH_OUTPUT            one row per canonical research output
--   FACT_CITATION_SNAPSHOT          one row per output/source/snapshot date
--   FACT_OUTPUT_SOURCE_OBSERVATION  one row per source observation version
--   FACT_OUTPUT_RELATION            one row per output/relation/target
--   BRIDGE_OUTPUT_AUTHOR            one row per output/author
--   BRIDGE_OUTPUT_TOPIC_CATEGORY    one row per output/category score
--   BRIDGE_AUTHOR_INSTITUTION       one row per author/institution

CREATE TABLE IF NOT EXISTS PAPERSONAR.PROJECT_DW.FACT_RESEARCH_OUTPUT (
  OUTPUT_SK           NUMBER(38,0)  NOT NULL,
  OUTPUT_BK           VARCHAR(300)  NOT NULL,
  DOI_NORMALIZED      VARCHAR(1000),
  PUBLICATION_DATE_KEY NUMBER(38,0) DEFAULT 0,
  PUBLICATION_DATE_SK NUMBER(38,0) DEFAULT 0,
  PUBLICATION_YEAR    NUMBER(38,0),
  OUTPUT_TYPE_KEY     VARCHAR(100) DEFAULT '-1',
  OUTPUT_TYPE_SK      NUMBER(38,0) DEFAULT 0,
  VENUE_KEY           VARCHAR(300) DEFAULT '-1',
  VENUE_SK            NUMBER(38,0) DEFAULT 0,
  ACCESS_STATUS_KEY   VARCHAR(50)  DEFAULT '-1',
  ACCESS_STATUS_SK    NUMBER(38,0) DEFAULT 0,
  SOURCE_SK           NUMBER(38,0) DEFAULT -1,
  SOURCE_NAME         VARCHAR(50),
  CITED_BY_COUNT      NUMBER(38,0) DEFAULT 0,
  OA_IS_OA            BOOLEAN DEFAULT FALSE,
  FIRST_SEEN_AT       TIMESTAMP_NTZ,
  LAST_SEEN_AT        TIMESTAMP_NTZ,
  LAST_BATCH_ID       VARCHAR(64),
  CONSTRAINT PK_FACT_RESEARCH_OUTPUT PRIMARY KEY (OUTPUT_SK)
)
COMMENT = 'Grain: one canonical research output; citation fields are winner-source values';

CREATE TABLE IF NOT EXISTS PAPERSONAR.PROJECT_DW.FACT_CITATION_SNAPSHOT (
  OUTPUT_SK          NUMBER(38,0) NOT NULL,
  SNAPSHOT_DATE_KEY  NUMBER(38,0) NOT NULL,
  SNAPSHOT_DATE_SK   NUMBER(38,0) NOT NULL,
  SOURCE_SK          NUMBER(38,0) DEFAULT -1,
  SOURCE_NAME        VARCHAR(50),
  CITED_BY_COUNT     NUMBER(38,0) DEFAULT 0,
  OA_IS_OA           BOOLEAN,
  OA_STATUS          VARCHAR(50),
  ACCESS_STATUS_SK   NUMBER(38,0) DEFAULT 0,
  BATCH_ID           VARCHAR(64),
  CONSTRAINT PK_FACT_CITATION_SNAPSHOT
    PRIMARY KEY (OUTPUT_SK, SOURCE_NAME, SNAPSHOT_DATE_KEY)
)
COMMENT = 'Grain: one output/source/snapshot date; source counts are never summed';

CREATE TABLE IF NOT EXISTS PAPERSONAR.PROJECT_DW.FACT_OUTPUT_SOURCE_OBSERVATION (
  OUTPUT_SK          NUMBER(38,0)   NOT NULL,
  SOURCE_SK          NUMBER(38,0)   DEFAULT -1,
  SOURCE_NAME        VARCHAR(50)    NOT NULL,
  ENTITY_NAME        VARCHAR(50)    NOT NULL,
  SOURCE_RECORD_ID   VARCHAR(1000)  NOT NULL,
  RECORD_HASH        VARCHAR(64)    NOT NULL,
  BATCH_ID           VARCHAR(64),
  INGESTED_AT        TIMESTAMP_NTZ,
  CONSTRAINT PK_FACT_OUTPUT_SOURCE_OBSERVATION
    PRIMARY KEY (OUTPUT_SK, SOURCE_NAME, ENTITY_NAME, SOURCE_RECORD_ID, RECORD_HASH)
)
COMMENT = 'Grain: one source observation version mapped to a canonical output';

CREATE TABLE IF NOT EXISTS PAPERSONAR.PROJECT_DW.FACT_OUTPUT_RELATION (
  OUTPUT_SK          NUMBER(38,0)  NOT NULL,
  RELATION_TYPE      VARCHAR(50)   NOT NULL,
  TARGET_DOI         VARCHAR(1000),
  TARGET_PROVIDER_ID VARCHAR(500),
  TARGET_OUTPUT_SK   NUMBER(38,0),
  SOURCE_NAME        VARCHAR(50),
  BATCH_ID           VARCHAR(64)
)
COMMENT = 'Grain: output/relation/target; unresolved targets keep their identifier';

CREATE TABLE IF NOT EXISTS PAPERSONAR.PROJECT_DW.BRIDGE_OUTPUT_AUTHOR (
  OUTPUT_SK       NUMBER(38,0)  NOT NULL,
  AUTHOR_SK       NUMBER(38,0)  NOT NULL,
  AUTHOR_KEY      VARCHAR(500)  NOT NULL,
  AUTHOR_POSITION NUMBER(38,0),
  SOURCE_NAME     VARCHAR(50),
  BATCH_ID        VARCHAR(64),
  CONSTRAINT PK_BRIDGE_OUTPUT_AUTHOR PRIMARY KEY (OUTPUT_SK, AUTHOR_KEY)
)
COMMENT = 'Grain: one output/author with source author position';

CREATE TABLE IF NOT EXISTS PAPERSONAR.PROJECT_DW.BRIDGE_OUTPUT_TOPIC_CATEGORY (
  OUTPUT_SK         NUMBER(38,0)  NOT NULL,
  CATEGORY_SK       NUMBER(38,0)  NOT NULL,
  CATEGORY_KEY      VARCHAR(80)  NOT NULL,
  SCORE             NUMBER(18,4),
  IS_PRIMARY        BOOLEAN,
  CATEGORY_RANK     NUMBER(38,0),
  METHOD            VARCHAR(20),
  TAXONOMY_VERSION  VARCHAR(20),
  BATCH_ID          VARCHAR(64),
  CONSTRAINT PK_BRIDGE_OUTPUT_TOPIC_CATEGORY PRIMARY KEY (OUTPUT_SK, CATEGORY_KEY)
)
COMMENT = 'Grain: one output/category with score and primary flag';

CREATE TABLE IF NOT EXISTS PAPERSONAR.PROJECT_DW.BRIDGE_AUTHOR_INSTITUTION (
  AUTHOR_SK        NUMBER(38,0)  NOT NULL,
  INSTITUTION_SK   NUMBER(38,0)  NOT NULL,
  AUTHOR_KEY       VARCHAR(500)  NOT NULL,
  INSTITUTION_KEY  VARCHAR(500)  NOT NULL,
  BATCH_ID         VARCHAR(64),
  CONSTRAINT PK_BRIDGE_AUTHOR_INSTITUTION
    PRIMARY KEY (AUTHOR_SK, INSTITUTION_SK)
)
COMMENT = 'Grain: one author/institution affiliation';

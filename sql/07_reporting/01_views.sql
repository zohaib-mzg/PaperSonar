-- =============================================================================
-- Purpose: Publish-only reporting views. A row is visible only when its
--          originating batch is present in PROJECT_AUDIT.PUBLISHED_BATCH.
-- Inputs: PROJECT_DW facts/dimensions, PROJECT_AUDIT batch/DQ tables.
-- Outputs: VW_RESEARCH_OUTPUT, VW_CITATION_SNAPSHOT, VW_SOURCE_OBSERVATION,
--          VW_CATEGORY_COVERAGE, VW_PIPELINE_HEALTH and grants.
-- Idempotent: Yes - CREATE OR REPLACE SECURE VIEW is safe for read-only objects.
-- Owner: PAPERSONAR_ADMIN
-- Parameters: None.
-- Cost: Query-time only; reporters use the shared XS warehouse.
-- =============================================================================
-- No unpublished batch is exposed. If a new batch updates a canonical output
-- but fails DQ, the output's previous published row is also hidden until the
-- batch is corrected and published; publication is intentionally fail-closed.

CREATE OR REPLACE SECURE VIEW PAPERSONAR.PROJECT_REPORTING.VW_PUBLISHED_BATCH AS
SELECT
  PUBLISHED.BATCH_ID,
  PUBLISHED.PUBLISHED_AT,
  PUBLISHED.PUBLISHED_BY,
  PUBLISHED.DQ_SUMMARY,
  BATCH.SOURCE_NAME,
  BATCH.ENTITY_NAME,
  BATCH.WINDOW_START,
  BATCH.WINDOW_END
FROM PAPERSONAR.PROJECT_AUDIT.PUBLISHED_BATCH PUBLISHED
JOIN PAPERSONAR.PROJECT_AUDIT.BATCH BATCH
  ON BATCH.BATCH_ID = PUBLISHED.BATCH_ID;

CREATE OR REPLACE SECURE VIEW PAPERSONAR.PROJECT_REPORTING.VW_RESEARCH_OUTPUT AS
SELECT
  FACT.OUTPUT_SK,
  FACT.OUTPUT_BK,
  FACT.DOI_NORMALIZED,
  FACT.PUBLICATION_YEAR,
  DATE_DIM.FULL_DATE AS PUBLICATION_DATE,
  TYPE_DIM.OUTPUT_TYPE_NAME,
  VENUE_DIM.VENUE_NAME,
  ACCESS_DIM.ACCESS_STATUS_NAME,
  SOURCE_DIM.SOURCE_NAME AS PRIMARY_SOURCE_NAME,
  FACT.CITED_BY_COUNT,
  FACT.OA_IS_OA,
  CATEGORY_DIM.CATEGORY_KEY,
  CATEGORY_DIM.LABEL AS CATEGORY_LABEL,
  BRIDGE.SCORE AS CATEGORY_SCORE,
  FACT.FIRST_SEEN_AT,
  FACT.LAST_SEEN_AT,
  FACT.LAST_BATCH_ID
FROM PAPERSONAR.PROJECT_DW.FACT_RESEARCH_OUTPUT FACT
LEFT JOIN PAPERSONAR.PROJECT_DW.DIM_DATE DATE_DIM
  ON DATE_DIM.DATE_SK = FACT.PUBLICATION_DATE_SK
LEFT JOIN PAPERSONAR.PROJECT_DW.DIM_OUTPUT_TYPE TYPE_DIM
  ON TYPE_DIM.OUTPUT_TYPE_SK = FACT.OUTPUT_TYPE_SK
LEFT JOIN PAPERSONAR.PROJECT_DW.DIM_VENUE VENUE_DIM
  ON VENUE_DIM.VENUE_SK = FACT.VENUE_SK
LEFT JOIN PAPERSONAR.PROJECT_DW.DIM_ACCESS_STATUS ACCESS_DIM
  ON ACCESS_DIM.ACCESS_STATUS_SK = FACT.ACCESS_STATUS_SK
LEFT JOIN PAPERSONAR.PROJECT_DW.DIM_SOURCE SOURCE_DIM
  ON SOURCE_DIM.SOURCE_SK = FACT.SOURCE_SK
LEFT JOIN PAPERSONAR.PROJECT_DW.BRIDGE_OUTPUT_TOPIC_CATEGORY BRIDGE
  ON BRIDGE.OUTPUT_SK = FACT.OUTPUT_SK AND BRIDGE.IS_PRIMARY
LEFT JOIN PAPERSONAR.PROJECT_DW.DIM_CATEGORY CATEGORY_DIM
  ON CATEGORY_DIM.CATEGORY_SK = BRIDGE.CATEGORY_SK
WHERE EXISTS (
  SELECT 1
  FROM PAPERSONAR.PROJECT_AUDIT.PUBLISHED_BATCH PUBLISHED
  WHERE PUBLISHED.BATCH_ID = FACT.LAST_BATCH_ID
);

CREATE OR REPLACE SECURE VIEW PAPERSONAR.PROJECT_REPORTING.VW_CITATION_SNAPSHOT AS
SELECT
  SNAPSHOT.OUTPUT_SK,
  OUTPUT_FACT.OUTPUT_BK,
  SNAPSHOT.SNAPSHOT_DATE_KEY,
  DATE_DIM.FULL_DATE AS SNAPSHOT_DATE,
  SNAPSHOT.SOURCE_NAME,
  SNAPSHOT.CITED_BY_COUNT,
  SNAPSHOT.OA_IS_OA,
  SNAPSHOT.OA_STATUS,
  ACCESS_DIM.ACCESS_STATUS_NAME
FROM PAPERSONAR.PROJECT_DW.FACT_CITATION_SNAPSHOT SNAPSHOT
JOIN PAPERSONAR.PROJECT_DW.FACT_RESEARCH_OUTPUT OUTPUT_FACT
  ON OUTPUT_FACT.OUTPUT_SK = SNAPSHOT.OUTPUT_SK
LEFT JOIN PAPERSONAR.PROJECT_DW.DIM_DATE DATE_DIM
  ON DATE_DIM.DATE_SK = SNAPSHOT.SNAPSHOT_DATE_SK
LEFT JOIN PAPERSONAR.PROJECT_DW.DIM_ACCESS_STATUS ACCESS_DIM
  ON ACCESS_DIM.ACCESS_STATUS_SK = SNAPSHOT.ACCESS_STATUS_SK
WHERE EXISTS (
  SELECT 1
  FROM PAPERSONAR.PROJECT_AUDIT.PUBLISHED_BATCH PUBLISHED
  WHERE PUBLISHED.BATCH_ID = SNAPSHOT.BATCH_ID
);

CREATE OR REPLACE SECURE VIEW PAPERSONAR.PROJECT_REPORTING.VW_SOURCE_OBSERVATION AS
SELECT
  OBSERVATION.OUTPUT_SK,
  OUTPUT_FACT.OUTPUT_BK,
  OBSERVATION.SOURCE_NAME,
  OBSERVATION.ENTITY_NAME,
  OBSERVATION.SOURCE_RECORD_ID,
  OBSERVATION.RECORD_HASH,
  OBSERVATION.INGESTED_AT,
  OBSERVATION.BATCH_ID
FROM PAPERSONAR.PROJECT_DW.FACT_OUTPUT_SOURCE_OBSERVATION OBSERVATION
JOIN PAPERSONAR.PROJECT_DW.FACT_RESEARCH_OUTPUT OUTPUT_FACT
  ON OUTPUT_FACT.OUTPUT_SK = OBSERVATION.OUTPUT_SK
WHERE EXISTS (
  SELECT 1
  FROM PAPERSONAR.PROJECT_AUDIT.PUBLISHED_BATCH PUBLISHED
  WHERE PUBLISHED.BATCH_ID = OBSERVATION.BATCH_ID
);

CREATE OR REPLACE SECURE VIEW PAPERSONAR.PROJECT_REPORTING.VW_CATEGORY_COVERAGE AS
SELECT
  CATEGORY_KEY,
  CATEGORY_LABEL,
  COUNT(*) AS OUTPUT_COUNT
FROM PAPERSONAR.PROJECT_REPORTING.VW_RESEARCH_OUTPUT
GROUP BY CATEGORY_KEY, CATEGORY_LABEL;

CREATE OR REPLACE SECURE VIEW PAPERSONAR.PROJECT_REPORTING.VW_PIPELINE_HEALTH AS
SELECT
  BATCH.BATCH_ID,
  BATCH.SOURCE_NAME,
  BATCH.ENTITY_NAME,
  BATCH.EXTRACTION_MODE,
  BATCH.WINDOW_START,
  BATCH.WINDOW_END,
  BATCH.STATUS,
  BATCH.FILE_COUNT,
  BATCH.RECORD_COUNT,
  BATCH.CREATED_AT,
  BATCH.FINISHED_AT,
  PUBLISHED.PUBLISHED_AT,
  (
    SELECT COUNT(*)
    FROM PAPERSONAR.PROJECT_AUDIT.DQ_RESULT DQ
    WHERE DQ.BATCH_ID = BATCH.BATCH_ID
      AND DQ.SEVERITY = 'CRITICAL'
      AND DQ.STATUS = 'FAIL'
  ) AS CRITICAL_DQ_FAILURES,
  (
    SELECT COUNT(*)
    FROM PAPERSONAR.PROJECT_AUDIT.DQ_RESULT DQ
    WHERE DQ.BATCH_ID = BATCH.BATCH_ID
      AND DQ.STATUS = 'FAIL'
  ) AS TOTAL_DQ_FAILURES
FROM PAPERSONAR.PROJECT_AUDIT.BATCH BATCH
LEFT JOIN PAPERSONAR.PROJECT_AUDIT.PUBLISHED_BATCH PUBLISHED
  ON PUBLISHED.BATCH_ID = BATCH.BATCH_ID;

GRANT SELECT ON VIEW PAPERSONAR.PROJECT_REPORTING.VW_PUBLISHED_BATCH
  TO ROLE PAPERSONAR_REPORTER;
GRANT SELECT ON VIEW PAPERSONAR.PROJECT_REPORTING.VW_RESEARCH_OUTPUT
  TO ROLE PAPERSONAR_REPORTER;
GRANT SELECT ON VIEW PAPERSONAR.PROJECT_REPORTING.VW_CITATION_SNAPSHOT
  TO ROLE PAPERSONAR_REPORTER;
GRANT SELECT ON VIEW PAPERSONAR.PROJECT_REPORTING.VW_SOURCE_OBSERVATION
  TO ROLE PAPERSONAR_REPORTER;
GRANT SELECT ON VIEW PAPERSONAR.PROJECT_REPORTING.VW_CATEGORY_COVERAGE
  TO ROLE PAPERSONAR_REPORTER;
GRANT SELECT ON VIEW PAPERSONAR.PROJECT_REPORTING.VW_PIPELINE_HEALTH
  TO ROLE PAPERSONAR_REPORTER;

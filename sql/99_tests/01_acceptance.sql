-- =============================================================================
-- Purpose: Read-only acceptance evidence queries. These are never deployed by
--          the runner; run them manually and save sanitized output under
--          docs/phase2/evidence/.
-- Inputs: all PaperSonar schemas.
-- Outputs: result sets only.
-- Idempotent: Yes - SELECT statements only.
-- Owner: PAPERSONAR_REPORTER (or PAPERSONAR_ADMIN for audit queries)
-- Parameters: session variable BATCH_ID.
-- Cost: Full-table counts; use the XS warehouse and run outside peak work.
-- =============================================================================
-- Usage:
--   SET BATCH_ID = '<batch id from PROJECT_AUDIT.BATCH>';
--   -- run each block separately and export CSV
--
-- These queries provide evidence; they do not mutate status or publish data.

-- 1. Layer reconciliation by source -----------------------------------------

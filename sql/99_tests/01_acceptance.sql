UNION ALL
SELECT 'STAGING_ARXIV', COUNT(*)
FROM PAPERSONAR.PROJECT_STAGING.STG_ARXIV_RECORD WHERE BATCH_ID = $BATCH_ID
UNION ALL
SELECT 'STAGING_DATACITE', COUNT(*)
FROM PAPERSONAR.PROJECT_STAGING.STG_DATACITE_DOI WHERE BATCH_ID = $BATCH_ID
UNION ALL
SELECT 'STAGING_ZENODO', COUNT(*)
FROM PAPERSONAR.PROJECT_STAGING.STG_ZENODO_RECORD WHERE BATCH_ID = $BATCH_ID
UNION ALL
SELECT 'BRONZE_OPENALEX', COUNT(*)
FROM PAPERSONAR.PROJECT_BRONZE.BRZ_OPENALEX_WORK WHERE BATCH_ID = $BATCH_ID
UNION ALL
SELECT 'BRONZE_CROSSREF', COUNT(*)
FROM PAPERSONAR.PROJECT_BRONZE.BRZ_CROSSREF_WORK WHERE BATCH_ID = $BATCH_ID
UNION ALL
SELECT 'BRONZE_ARXIV', COUNT(*)
FROM PAPERSONAR.PROJECT_BRONZE.BRZ_ARXIV_RECORD WHERE BATCH_ID = $BATCH_ID
UNION ALL
SELECT 'BRONZE_DATACITE', COUNT(*)
FROM PAPERSONAR.PROJECT_BRONZE.BRZ_DATACITE_DOI WHERE BATCH_ID = $BATCH_ID
UNION ALL
SELECT 'BRONZE_ZENODO', COUNT(*)
FROM PAPERSONAR.PROJECT_BRONZE.BRZ_ZENODO_RECORD WHERE BATCH_ID = $BATCH_ID
UNION ALL
SELECT 'SILVER_OBSERVATION', COUNT(*)
FROM PAPERSONAR.PROJECT_SILVER.SLV_SOURCE_OBSERVATION WHERE BATCH_ID = $BATCH_ID
UNION ALL
SELECT 'SILVER_CROSSWALK', COUNT(*)
FROM PAPERSONAR.PROJECT_SILVER.SLV_OUTPUT_CROSSWALK WHERE BATCH_ID = $BATCH_ID
UNION ALL
SELECT 'QUARANTINE', COUNT(*)
FROM PAPERSONAR.PROJECT_AUDIT.QUARANTINE_RECORD WHERE BATCH_ID = $BATCH_ID
UNION ALL
SELECT 'DW_OUTPUT', COUNT(*)
FROM PAPERSONAR.PROJECT_DW.FACT_RESEARCH_OUTPUT WHERE LAST_BATCH_ID = $BATCH_ID
ORDER BY LAYER;

-- 2. Dimension population (acceptance target: >= 100 total rows) -------------
SELECT 'DIM_AUTHOR' AS OBJECT_NAME, COUNT(*) AS ROW_COUNT,
       COUNT(DISTINCT AUTHOR_KEY) AS BUSINESS_MEMBERS
FROM PAPERSONAR.PROJECT_DW.DIM_AUTHOR
UNION ALL
SELECT 'DIM_INSTITUTION', COUNT(*), COUNT(DISTINCT INSTITUTION_KEY)
FROM PAPERSONAR.PROJECT_DW.DIM_INSTITUTION
UNION ALL
SELECT 'DIM_VENUE', COUNT(*), COUNT(DISTINCT VENUE_KEY)
FROM PAPERSONAR.PROJECT_DW.DIM_VENUE
UNION ALL
SELECT 'DIM_TOPIC', COUNT(*), COUNT(DISTINCT TOPIC_KEY)
FROM PAPERSONAR.PROJECT_DW.DIM_TOPIC
UNION ALL
SELECT 'DIM_CATEGORY', COUNT(*), COUNT(DISTINCT CATEGORY_KEY)
FROM PAPERSONAR.PROJECT_DW.DIM_CATEGORY
UNION ALL
SELECT 'DIM_OUTPUT_TYPE', COUNT(*), COUNT(DISTINCT OUTPUT_TYPE_KEY)
FROM PAPERSONAR.PROJECT_DW.DIM_OUTPUT_TYPE
UNION ALL
SELECT 'DIM_ACCESS_STATUS', COUNT(*), COUNT(DISTINCT ACCESS_STATUS_KEY)
FROM PAPERSONAR.PROJECT_DW.DIM_ACCESS_STATUS
UNION ALL
SELECT 'DIM_DATE', COUNT(*), COUNT(DISTINCT DATE_KEY)
FROM PAPERSONAR.PROJECT_DW.DIM_DATE
ORDER BY OBJECT_NAME;


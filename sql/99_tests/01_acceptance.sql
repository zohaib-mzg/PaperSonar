UNION ALL
SELECT 'FACT_OUTPUT_SOURCE_OBSERVATION', COUNT(*)
FROM PAPERSONAR.PROJECT_DW.FACT_OUTPUT_SOURCE_OBSERVATION
UNION ALL
SELECT 'FACT_OUTPUT_RELATION', COUNT(*)
FROM PAPERSONAR.PROJECT_DW.FACT_OUTPUT_RELATION

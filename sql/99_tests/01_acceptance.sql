-- 4. Zero-orphan evidence (every result must be 0) ---------------------------
SELECT 'fact_output_type' AS CHECK_NAME, COUNT(*) AS ORPHAN_ROWS
FROM PAPERSONAR.PROJECT_DW.FACT_RESEARCH_OUTPUT f
LEFT JOIN PAPERSONAR.PROJECT_DW.DIM_OUTPUT_TYPE d
  ON d.OUTPUT_TYPE_SK = f.OUTPUT_TYPE_SK
WHERE d.OUTPUT_TYPE_SK IS NULL
UNION ALL
SELECT 'fact_venue', COUNT(*)
FROM PAPERSONAR.PROJECT_DW.FACT_RESEARCH_OUTPUT f
LEFT JOIN PAPERSONAR.PROJECT_DW.DIM_VENUE d ON d.VENUE_SK = f.VENUE_SK
WHERE d.VENUE_SK IS NULL
UNION ALL
SELECT 'fact_access_status', COUNT(*)
FROM PAPERSONAR.PROJECT_DW.FACT_RESEARCH_OUTPUT f
LEFT JOIN PAPERSONAR.PROJECT_DW.DIM_ACCESS_STATUS d
  ON d.ACCESS_STATUS_SK = f.ACCESS_STATUS_SK
WHERE d.ACCESS_STATUS_SK IS NULL
UNION ALL
SELECT 'fact_source', COUNT(*)
FROM PAPERSONAR.PROJECT_DW.FACT_RESEARCH_OUTPUT f
LEFT JOIN PAPERSONAR.PROJECT_DW.DIM_SOURCE d ON d.SOURCE_SK = f.SOURCE_SK
WHERE d.SOURCE_SK IS NULL
UNION ALL
SELECT 'fact_publication_date', COUNT(*)
FROM PAPERSONAR.PROJECT_DW.FACT_RESEARCH_OUTPUT f
LEFT JOIN PAPERSONAR.PROJECT_DW.DIM_DATE d
  ON d.DATE_SK = f.PUBLICATION_DATE_SK
WHERE f.PUBLICATION_DATE_SK <> 0 AND d.DATE_SK IS NULL
UNION ALL
SELECT 'bridge_output_author_author', COUNT(*)
FROM PAPERSONAR.PROJECT_DW.BRIDGE_OUTPUT_AUTHOR b
LEFT JOIN PAPERSONAR.PROJECT_DW.DIM_AUTHOR d
  ON d.AUTHOR_SK = b.AUTHOR_SK
WHERE d.AUTHOR_SK IS NULL
UNION ALL
SELECT 'bridge_output_author_output', COUNT(*)
FROM PAPERSONAR.PROJECT_DW.BRIDGE_OUTPUT_AUTHOR b
LEFT JOIN PAPERSONAR.PROJECT_DW.DIMENSION_KEY_MAP d
  ON d.DIMENSION_NAME = 'OUTPUT' AND d.SURROGATE_KEY = b.OUTPUT_SK
WHERE d.SURROGATE_KEY IS NULL
UNION ALL
SELECT 'bridge_category', COUNT(*)
FROM PAPERSONAR.PROJECT_DW.BRIDGE_OUTPUT_TOPIC_CATEGORY b
LEFT JOIN PAPERSONAR.PROJECT_DW.DIM_CATEGORY d
  ON d.CATEGORY_SK = b.CATEGORY_SK
WHERE d.CATEGORY_SK IS NULL
UNION ALL
SELECT 'bridge_author_institution_author', COUNT(*)
FROM PAPERSONAR.PROJECT_DW.BRIDGE_AUTHOR_INSTITUTION b
LEFT JOIN PAPERSONAR.PROJECT_DW.DIM_AUTHOR d
  ON d.AUTHOR_SK = b.AUTHOR_SK
WHERE d.AUTHOR_SK IS NULL
UNION ALL
SELECT 'bridge_author_institution_institution', COUNT(*)
FROM PAPERSONAR.PROJECT_DW.BRIDGE_AUTHOR_INSTITUTION b
LEFT JOIN PAPERSONAR.PROJECT_DW.DIM_INSTITUTION d
  ON d.INSTITUTION_SK = b.INSTITUTION_SK
WHERE d.INSTITUTION_SK IS NULL
ORDER BY CHECK_NAME;

-- 5. DQ gate evidence --------------------------------------------------------
SELECT RULE_ID, LAYER, SEVERITY, STATUS, OBSERVED_VALUE, THRESHOLD_VALUE,
       DESCRIPTION, CHECKED_AT
FROM PAPERSONAR.PROJECT_AUDIT.DQ_RESULT
WHERE BATCH_ID = $BATCH_ID
ORDER BY RULE_ID;

SELECT BATCH_ID, STATUS, FILE_COUNT, RECORD_COUNT, ERROR_SUMMARY
FROM PAPERSONAR.PROJECT_AUDIT.BATCH
WHERE BATCH_ID = $BATCH_ID;

SELECT BATCH_ID, PUBLISHED_AT, PUBLISHED_BY, DQ_SUMMARY
FROM PAPERSONAR.PROJECT_AUDIT.PUBLISHED_BATCH
WHERE BATCH_ID = $BATCH_ID;

-- 6. Stable key snapshot (rerun and compare) --------------------------------
SELECT DIMENSION_NAME, BUSINESS_KEY, SURROGATE_KEY
FROM PAPERSONAR.PROJECT_DW.DIMENSION_KEY_MAP
ORDER BY DIMENSION_NAME, BUSINESS_KEY;

SELECT AUTHOR_KEY, AUTHOR_SK, VERSION, IS_CURRENT, EFFECTIVE_FROM, EFFECTIVE_TO
FROM PAPERSONAR.PROJECT_DW.DIM_AUTHOR
ORDER BY AUTHOR_KEY, VERSION;

-- 7. Watermark evidence ------------------------------------------------------
SELECT SOURCE_NAME, ENTITY_NAME, WATERMARK_VALUE, WINDOW_START, WINDOW_END,
       LAST_BATCH_ID, LAST_SUCCESS_AT, STATUS
FROM PAPERSONAR.PROJECT_AUDIT.SOURCE_WATERMARK
ORDER BY SOURCE_NAME, ENTITY_NAME;

-- 8. Task-graph history (account-level; replace the time range) --------------
SELECT NAME, STATE, SCHEDULED_TIME, COMPLETED_TIME, ERROR_CODE, ERROR_MESSAGE
FROM TABLE(PAPERSONAR.INFORMATION_SCHEMA.TASK_HISTORY(
  SCHEDULED_TIME_RANGE_START => DATEADD('hour', -24, CURRENT_TIMESTAMP())
))
ORDER BY SCHEDULED_TIME DESC;

-- 9. Published-view evidence (must match the published batch only) -----------
SELECT * FROM PAPERSONAR.PROJECT_REPORTING.VW_PIPELINE_HEALTH

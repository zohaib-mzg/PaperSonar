-- =============================================================================
-- PaperSonar Phase 2 - Snowflake-side verification pack (READ-ONLY)
-- =============================================================================
-- Purpose: Prove what Phase 2 actually built inside Snowflake: schemas,
--          roles, warehouse controls, task graph, pipeline state, data quality,
--          dimensional model, publication contract and data readiness for Phase 3.
-- Inputs: database PAPERSONAR (all schemas). No writes, no DDL.
-- Outputs: result sets only; copy each block into a Snowflake worksheet and
--          save the results as sanitized evidence under docs/phase2/evidence/.
-- Idempotent: Yes - SELECT/SHOW only. Safe to re-run.
-- Owner: PAPERSONAR_ADMIN (ACCOUNTADMIN acceptable for this audit only;
--        automation must never use ACCOUNTADMIN).
-- Parameters: none (all queries are self-contained).
-- Cost: mostly metadata; the marked [SCAN] queries touch fact tables and read
--        compressed data, so run them on WH_PAPERSONAR_ELT outside peak time.
-- Notes:   Run blocks in order. Each block is self-contained.
-- =============================================================================

-- ============================================================================
-- SECTION A - ENVIRONMENT, COST GUARDS AND OBJECT INVENTORY
-- ============================================================================

-- A1. Account context, current role, warehouse, session and trial context ---
SELECT CURRENT_ACCOUNT()  AS ACCOUNT,
       CURRENT_USER()     AS SESSION_USER,
       CURRENT_ROLE()     AS SESSION_ROLE,
       CURRENT_DATABASE() AS DATABASE,
       CURRENT_WAREHOUSE() AS WAREHOUSE,
       CURRENT_TIMESTAMP() AS RUN_AT_UTC;

-- A2. Warehouse cost controls (expect XSMALL, AUTO_SUSPEND 60, RESUMING/SUSPENDED)
SHOW WAREHOUSES LIKE 'WH_PAPERSONAR_ELT';

-- A3. All schemas present (expect exactly 7 PaperSonar schemas) --------------
SELECT SCHEMA_NAME
FROM PAPERSONAR.INFORMATION_SCHEMA.SCHEMATA
WHERE SCHEMA_NAME LIKE 'PROJECT_%'
ORDER BY SCHEMA_NAME;

-- A4. Roles present (expect 4 PaperSonar roles) -------------------------------
SHOW ROLES LIKE 'PAPERSONAR%';

-- A5. Which users hold which PaperSonar role ---------------------------------
SHOW USERS;

-- A6. Object inventory by schema and type (tables/views/procedures/functions) --
SELECT TABLE_SCHEMA AS SCHEMA_NAME,
       TABLE_TYPE   AS OBJECT_TYPE,
       COUNT(*)     AS OBJECT_COUNT
FROM PAPERSONAR.INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA LIKE 'PROJECT_%'
GROUP BY TABLE_SCHEMA, TABLE_TYPE
ORDER BY TABLE_SCHEMA, OBJECT_TYPE;

-- A7. Full table list with row counts from metadata (no scan) ----------------
SELECT TABLE_SCHEMA AS SCHEMA_NAME,
       TABLE_NAME,
       ROW_COUNT
FROM PAPERSONAR.INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA LIKE 'PROJECT_%'
  AND TABLE_TYPE = 'BASE TABLE'
ORDER BY TABLE_SCHEMA, TABLE_NAME;

-- A8. Views present (expect 6 reporting views + any others) -------------------
SELECT TABLE_SCHEMA AS SCHEMA_NAME, TABLE_NAME
FROM PAPERSONAR.INFORMATION_SCHEMA.VIEWS
WHERE TABLE_SCHEMA LIKE 'PROJECT_%'
ORDER BY TABLE_SCHEMA, TABLE_NAME;

-- A9. Procedures and UDFs -----------------------------------------------------
SELECT TABLE_SCHEMA AS SCHEMA_NAME,
       TABLE_NAME,
       TABLE_TYPE
FROM PAPERSONAR.INFORMATION_SCHEMA.PROCEDURES
WHERE TABLE_SCHEMA LIKE 'PROJECT_%'
ORDER BY TABLE_SCHEMA, TABLE_NAME;

-- A10. Physical-design demonstrations (materialized view + dynamic table) ----
SHOW MATERIALIZED VIEWS IN PAPERSONAR.PROJECT_REPORTING;
SHOW DYNAMIC TABLES IN PAPERSONAR.PROJECT_REPORTING;

-- A11. Stages and file formats -----------------------------------------------
SHOW STAGES IN PAPERSONAR.PROJECT_STAGING;
SHOW FILE FORMATS IN PAPERSONAR.PROJECT_STAGING;

-- ============================================================================
-- SECTION B - TASK GRAPH AND SCHEDULER CONTRACT
-- ============================================================================

-- B1. Task inventory and state.
-- EXPECTED: 9 child/finalizer tasks = 'started'; TASK_ELT_ROOT = 'suspended'
-- (root has no SCHEDULE by design; GitHub Actions is the only scheduler).
SHOW TASKS IN SCHEMA PAPERSONAR.PROJECT_AUDIT;

-- B2. Task summary: count started vs suspended -------------------------------
SELECT STATE, COUNT(*) AS TASK_COUNT
FROM TABLE(PAPERSONAR.INFORMATION_SCHEMA.TASKS)
WHERE DATABASE_NAME = 'PAPERSONAR'
  AND SCHEMA_NAME = 'PROJECT_AUDIT'
GROUP BY STATE
ORDER BY STATE;

-- B3. Confirm the root has NO Snowflake schedule (GitHub-only scheduler) ------
-- SCHEDULED_TIME must be NULL for the root: no Snowflake cron exists.
-- Cross-check in the B1 grid (SHOW TASKS): the root's "schedule" column is empty.
SELECT NAME, STATE, SCHEDULED_TIME, CONDITION, DEFINITION
FROM TABLE(PAPERSONAR.INFORMATION_SCHEMA.TASKS)
WHERE DATABASE_NAME = 'PAPERSONAR'
  AND SCHEMA_NAME = 'PROJECT_AUDIT'
  AND NAME = 'TASK_ELT_ROOT';

-- B4. Task run history (last 72h). Expect the OpenAlex publication pass. ----
SELECT NAME, SCHEDULED_TIME, COMPLETED_TIME, STATE, ERROR_CODE, ERROR_MESSAGE
FROM TABLE(PAPERSONAR.INFORMATION_SCHEMA.TASK_HISTORY(
  SCHEDULED_TIME_RANGE_START => DATEADD('hour', -72, CURRENT_TIMESTAMP()),
  RESULT_LIMIT => 200
))
ORDER BY SCHEDULED_TIME DESC, NAME;

-- ============================================================================
-- SECTION C - PIPELINE STATE, LIFECYCLE AND AUDIT TRAIL
-- ============================================================================

-- C1. Every batch ever created, newest first --------------------------------
SELECT BATCH_ID, SOURCE_NAME, ENTITY_NAME, EXTRACTION_MODE,
       WINDOW_START, WINDOW_END, STATUS, FILE_COUNT, RECORD_COUNT,
       IS_CAPPED, CURSOR_END, ERROR_SUMMARY, CREATED_AT, FINISHED_AT
FROM PAPERSONAR.PROJECT_AUDIT.BATCH
ORDER BY CREATED_AT DESC;

-- C2. Published batches (the publication contract) ---------------------------
SELECT BATCH_ID, PUBLISHED_AT, PUBLISHED_BY, DQ_SUMMARY, IS_CAPPED
FROM PAPERSONAR.PROJECT_AUDIT.PUBLISHED_BATCH
ORDER BY PUBLISHED_AT DESC;

-- C3. Batch status rollup ----------------------------------------------------
SELECT STATUS, COUNT(*) AS BATCH_COUNT, SUM(RECORD_COUNT) AS TOTAL_RECORDS
FROM PAPERSONAR.PROJECT_AUDIT.BATCH
GROUP BY STATUS
ORDER BY STATUS;

-- C4. Stage-by-stage execution log for the published batch --------------------
SELECT STAGE, STATUS, STARTED_AT, FINISHED_AT, ROW_COUNT,
       RETRY_COUNT, ERROR_SUMMARY, QUERY_ID, IMPLEMENTATION_VERSION
FROM PAPERSONAR.PROJECT_AUDIT.RUN_LOG
ORDER BY STARTED_AT DESC, STAGE;

-- C5. File load reconciliation (manifest rows vs staged rows) ----------------
SELECT BATCH_ID, SOURCE_NAME, FILE_NAME, STAGED_ROWS, MANIFEST_ROWS, STATUS, LOADED_AT
FROM PAPERSONAR.PROJECT_AUDIT.FILE_LOAD_LOG
ORDER BY LOADED_AT DESC;

-- C6. Manifest registry -------------------------------------------------------
SELECT BATCH_ID, SOURCE_NAME, FILE_NAME, RECORD_COUNT, FILE_SIZE_BYTES,
       CHECKSUM, STATUS, EXTRACTED_AT, LOADED_AT
FROM PAPERSONAR.PROJECT_AUDIT.BATCH_MANIFEST
ORDER BY EXTRACTED_AT DESC;

-- C7. DQ gate results for every batch (severity, rule, status) ----------------
SELECT BATCH_ID, RULE_ID, SEVERITY, STATUS, OBSERVED_VALUE, THRESHOLD_VALUE,
       LAYER, DESCRIPTION, CHECKED_AT
FROM PAPERSONAR.PROJECT_AUDIT.DQ_RESULT
ORDER BY BATCH_ID, RULE_ID;

-- C8. DQ rollup: critical failures must be 0 for a published batch -----------
SELECT BATCH_ID,
       COUNT(*) AS RULES_EVALUATED,
       COUNT_IF(SEVERITY = 'CRITICAL') AS CRITICAL_RULES,
       COUNT_IF(SEVERITY = 'CRITICAL' AND STATUS = 'FAIL') AS CRITICAL_FAILURES,
       COUNT_IF(SEVERITY = 'WARNING' AND STATUS = 'FAIL') AS WARNING_FAILURES,
       COUNT_IF(STATUS = 'PASS') AS RULES_PASSED
FROM PAPERSONAR.PROJECT_AUDIT.DQ_RESULT
GROUP BY BATCH_ID
ORDER BY BATCH_ID;

-- C9. Watermarks (must advance only after publication) -----------------------
SELECT SOURCE_NAME, ENTITY_NAME, WATERMARK_VALUE, WINDOW_START, WINDOW_END,
       OVERLAP_DAYS, LAST_BATCH_ID, LAST_SUCCESS_AT, STATUS, UPDATED_AT
FROM PAPERSONAR.PROJECT_AUDIT.SOURCE_WATERMARK
ORDER BY SOURCE_NAME, ENTITY_NAME;

-- C10. Stuck-batch check (CURRENT_BATCH must be empty when nothing is running)
SELECT * FROM PAPERSONAR.PROJECT_AUDIT.CURRENT_BATCH;

-- C11. Quarantine: malformed records are visible, never dropped ----------------
SELECT BATCH_ID, SOURCE_NAME, REASON_CODE, COUNT(*) AS RECORDS
FROM PAPERSONAR.PROJECT_AUDIT.QUARANTINE_RECORD
GROUP BY BATCH_ID, SOURCE_NAME, REASON_CODE
ORDER BY BATCH_ID, RECORDS DESC;

-- C12. Schema drift log ------------------------------------------------------
SELECT DRIFT_ID, BATCH_ID, SOURCE_NAME, ENTITY_NAME, KEY_NAME, DRIFT_TYPE,
       IS_REQUIRED, FIRST_SEEN_AT
FROM PAPERSONAR.PROJECT_AUDIT.SCHEMA_DRIFT_LOG
ORDER BY FIRST_SEEN_AT DESC;

-- C13. Lineage events (source -> canonical traceability) ---------------------
SELECT EVENT_ID, BATCH_ID, LAYER, OBJECT_NAME, EVENT_TYPE,
       INPUT_COUNT, OUTPUT_COUNT, EVENT_AT
FROM PAPERSONAR.PROJECT_AUDIT.LINEAGE_EVENT
ORDER BY EVENT_AT DESC;


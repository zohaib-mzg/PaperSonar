-- 005_dimensional_surrogate_keys.sql
-- Add numeric warehouse surrogate keys while retaining source/business keys.
-- The generic map is the durable business-key -> surrogate-key crosswalk.
-- This migration is additive and repeatable; existing fact/bridge natural-key
-- columns remain in place for lineage and idempotent MERGE matching.

CREATE SEQUENCE IF NOT EXISTS PROJECT_DW.SEQ_DIMENSION_SURROGATE_KEY
  START = 1 INCREMENT = 1;

CREATE TABLE IF NOT EXISTS PROJECT_DW.DIMENSION_KEY_MAP (
  SURROGATE_KEY NUMBER NOT NULL DEFAULT PROJECT_DW.SEQ_DIMENSION_SURROGATE_KEY.NEXTVAL,
  DIMENSION_NAME STRING NOT NULL,
  BUSINESS_KEY STRING NOT NULL,
  CREATED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(),
  CONSTRAINT PK_DIMENSION_KEY_MAP PRIMARY KEY (DIMENSION_NAME, BUSINESS_KEY)
)
COMMENT = 'Stable numeric warehouse surrogate key mapped from a dimension business key.';

-- Add the surrogate identifier to every existing dimension.
ALTER TABLE PROJECT_DW.DIM_WORK ADD COLUMN IF NOT EXISTS WORK_SK NUMBER;
ALTER TABLE PROJECT_DW.DIM_DATE ADD COLUMN IF NOT EXISTS DATE_SK NUMBER;
ALTER TABLE PROJECT_DW.DIM_TOPIC ADD COLUMN IF NOT EXISTS TOPIC_SK NUMBER;
ALTER TABLE PROJECT_DW.DIM_VENUE ADD COLUMN IF NOT EXISTS VENUE_SK NUMBER;
ALTER TABLE PROJECT_DW.DIM_WORK_TYPE ADD COLUMN IF NOT EXISTS WORK_TYPE_SK NUMBER;
ALTER TABLE PROJECT_DW.DIM_ACCESS_STATUS ADD COLUMN IF NOT EXISTS ACCESS_STATUS_SK NUMBER;
ALTER TABLE PROJECT_DW.DIM_AUTHOR ADD COLUMN IF NOT EXISTS AUTHOR_SK NUMBER;
ALTER TABLE PROJECT_DW.DIM_INSTITUTION ADD COLUMN IF NOT EXISTS INSTITUTION_SK NUMBER;

-- Keep natural/source identifiers in place and add numeric fact/bridge references.
ALTER TABLE PROJECT_DW.WORK_SOURCE_XW ADD COLUMN IF NOT EXISTS WORK_SK NUMBER;
ALTER TABLE PROJECT_DW.FACT_PUBLICATION ADD COLUMN IF NOT EXISTS WORK_SK NUMBER;
ALTER TABLE PROJECT_DW.FACT_PUBLICATION ADD COLUMN IF NOT EXISTS PUBLICATION_DATE_KEY NUMBER;
ALTER TABLE PROJECT_DW.FACT_PUBLICATION ADD COLUMN IF NOT EXISTS PUBLICATION_DATE_SK NUMBER;
ALTER TABLE PROJECT_DW.FACT_PUBLICATION ADD COLUMN IF NOT EXISTS WORK_TYPE_SK NUMBER;
ALTER TABLE PROJECT_DW.FACT_PUBLICATION ADD COLUMN IF NOT EXISTS VENUE_SK NUMBER;
ALTER TABLE PROJECT_DW.FACT_PUBLICATION ADD COLUMN IF NOT EXISTS ACCESS_STATUS_SK NUMBER;
ALTER TABLE PROJECT_DW.FACT_WORK_SNAPSHOT ADD COLUMN IF NOT EXISTS WORK_SK NUMBER;
ALTER TABLE PROJECT_DW.FACT_WORK_SNAPSHOT ADD COLUMN IF NOT EXISTS SNAPSHOT_DATE_SK NUMBER;
ALTER TABLE PROJECT_DW.FACT_WORK_SNAPSHOT ADD COLUMN IF NOT EXISTS ACCESS_STATUS_KEY STRING;
ALTER TABLE PROJECT_DW.FACT_WORK_SNAPSHOT ADD COLUMN IF NOT EXISTS ACCESS_STATUS_SK NUMBER;
ALTER TABLE PROJECT_DW.FACT_CITATION ADD COLUMN IF NOT EXISTS WORK_SK NUMBER;
ALTER TABLE PROJECT_DW.FACT_CITATION ADD COLUMN IF NOT EXISTS CITED_WORK_SK NUMBER;
ALTER TABLE PROJECT_DW.BRIDGE_WORK_TOPIC ADD COLUMN IF NOT EXISTS WORK_SK NUMBER;
ALTER TABLE PROJECT_DW.BRIDGE_WORK_TOPIC ADD COLUMN IF NOT EXISTS TOPIC_SK NUMBER;
ALTER TABLE PROJECT_DW.BRIDGE_WORK_AUTHOR ADD COLUMN IF NOT EXISTS WORK_SK NUMBER;
ALTER TABLE PROJECT_DW.BRIDGE_WORK_AUTHOR ADD COLUMN IF NOT EXISTS AUTHOR_SK NUMBER;
ALTER TABLE PROJECT_DW.BRIDGE_WORK_INSTITUTION ADD COLUMN IF NOT EXISTS WORK_SK NUMBER;
ALTER TABLE PROJECT_DW.BRIDGE_WORK_INSTITUTION ADD COLUMN IF NOT EXISTS INSTITUTION_SK NUMBER;
ALTER TABLE PROJECT_DW.BRIDGE_WORK_INSTITUTION ADD COLUMN IF NOT EXISTS AUTHOR_SK NUMBER;

-- Map all existing dimension business keys. Inserts omit SURROGATE_KEY so the
-- Snowflake sequence assigns a stable numeric identifier. NOT EXISTS permits
-- safe re-execution after an interrupted migration.
INSERT INTO PROJECT_DW.DIMENSION_KEY_MAP (DIMENSION_NAME, BUSINESS_KEY)
SELECT DISTINCT 'WORK', TO_VARCHAR(d.WORK_KEY)
FROM PROJECT_DW.DIM_WORK d
WHERE d.WORK_KEY IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM PROJECT_DW.DIMENSION_KEY_MAP m
                  WHERE m.DIMENSION_NAME = 'WORK' AND m.BUSINESS_KEY = TO_VARCHAR(d.WORK_KEY));

INSERT INTO PROJECT_DW.DIMENSION_KEY_MAP (DIMENSION_NAME, BUSINESS_KEY)
SELECT DISTINCT 'DATE', TO_VARCHAR(d.DATE_KEY)
FROM PROJECT_DW.DIM_DATE d
WHERE d.DATE_KEY IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM PROJECT_DW.DIMENSION_KEY_MAP m
                  WHERE m.DIMENSION_NAME = 'DATE' AND m.BUSINESS_KEY = TO_VARCHAR(d.DATE_KEY));

INSERT INTO PROJECT_DW.DIMENSION_KEY_MAP (DIMENSION_NAME, BUSINESS_KEY)
SELECT DISTINCT 'TOPIC', TO_VARCHAR(d.TOPIC_KEY)
FROM PROJECT_DW.DIM_TOPIC d
WHERE d.TOPIC_KEY IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM PROJECT_DW.DIMENSION_KEY_MAP m
                  WHERE m.DIMENSION_NAME = 'TOPIC' AND m.BUSINESS_KEY = TO_VARCHAR(d.TOPIC_KEY));

INSERT INTO PROJECT_DW.DIMENSION_KEY_MAP (DIMENSION_NAME, BUSINESS_KEY)
SELECT DISTINCT 'VENUE', TO_VARCHAR(d.VENUE_KEY)
FROM PROJECT_DW.DIM_VENUE d
WHERE d.VENUE_KEY IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM PROJECT_DW.DIMENSION_KEY_MAP m
                  WHERE m.DIMENSION_NAME = 'VENUE' AND m.BUSINESS_KEY = TO_VARCHAR(d.VENUE_KEY));

INSERT INTO PROJECT_DW.DIMENSION_KEY_MAP (DIMENSION_NAME, BUSINESS_KEY)
SELECT DISTINCT 'WORK_TYPE', TO_VARCHAR(d.WORK_TYPE_KEY)
FROM PROJECT_DW.DIM_WORK_TYPE d
WHERE d.WORK_TYPE_KEY IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM PROJECT_DW.DIMENSION_KEY_MAP m
                  WHERE m.DIMENSION_NAME = 'WORK_TYPE' AND m.BUSINESS_KEY = TO_VARCHAR(d.WORK_TYPE_KEY));

INSERT INTO PROJECT_DW.DIMENSION_KEY_MAP (DIMENSION_NAME, BUSINESS_KEY)
SELECT DISTINCT 'ACCESS_STATUS', TO_VARCHAR(d.ACCESS_STATUS_KEY)
FROM PROJECT_DW.DIM_ACCESS_STATUS d
WHERE d.ACCESS_STATUS_KEY IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM PROJECT_DW.DIMENSION_KEY_MAP m
                  WHERE m.DIMENSION_NAME = 'ACCESS_STATUS' AND m.BUSINESS_KEY = TO_VARCHAR(d.ACCESS_STATUS_KEY));

INSERT INTO PROJECT_DW.DIMENSION_KEY_MAP (DIMENSION_NAME, BUSINESS_KEY)
SELECT DISTINCT 'AUTHOR', TO_VARCHAR(d.AUTHOR_KEY)
FROM PROJECT_DW.DIM_AUTHOR d
WHERE d.AUTHOR_KEY IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM PROJECT_DW.DIMENSION_KEY_MAP m
                  WHERE m.DIMENSION_NAME = 'AUTHOR' AND m.BUSINESS_KEY = TO_VARCHAR(d.AUTHOR_KEY));

INSERT INTO PROJECT_DW.DIMENSION_KEY_MAP (DIMENSION_NAME, BUSINESS_KEY)
SELECT DISTINCT 'INSTITUTION', TO_VARCHAR(d.INSTITUTION_KEY)
FROM PROJECT_DW.DIM_INSTITUTION d
WHERE d.INSTITUTION_KEY IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM PROJECT_DW.DIMENSION_KEY_MAP m
                  WHERE m.DIMENSION_NAME = 'INSTITUTION' AND m.BUSINESS_KEY = TO_VARCHAR(d.INSTITUTION_KEY));

-- Backfill dimension surrogate columns without changing existing business keys.
UPDATE PROJECT_DW.DIM_WORK d SET WORK_SK = m.SURROGATE_KEY
FROM PROJECT_DW.DIMENSION_KEY_MAP m
WHERE d.WORK_SK IS NULL AND m.DIMENSION_NAME = 'WORK' AND m.BUSINESS_KEY = TO_VARCHAR(d.WORK_KEY);
UPDATE PROJECT_DW.DIM_DATE d SET DATE_SK = m.SURROGATE_KEY
FROM PROJECT_DW.DIMENSION_KEY_MAP m
WHERE d.DATE_SK IS NULL AND m.DIMENSION_NAME = 'DATE' AND m.BUSINESS_KEY = TO_VARCHAR(d.DATE_KEY);
UPDATE PROJECT_DW.DIM_TOPIC d SET TOPIC_SK = m.SURROGATE_KEY
FROM PROJECT_DW.DIMENSION_KEY_MAP m
WHERE d.TOPIC_SK IS NULL AND m.DIMENSION_NAME = 'TOPIC' AND m.BUSINESS_KEY = TO_VARCHAR(d.TOPIC_KEY);
UPDATE PROJECT_DW.DIM_VENUE d SET VENUE_SK = m.SURROGATE_KEY
FROM PROJECT_DW.DIMENSION_KEY_MAP m
WHERE d.VENUE_SK IS NULL AND m.DIMENSION_NAME = 'VENUE' AND m.BUSINESS_KEY = TO_VARCHAR(d.VENUE_KEY);
UPDATE PROJECT_DW.DIM_WORK_TYPE d SET WORK_TYPE_SK = m.SURROGATE_KEY
FROM PROJECT_DW.DIMENSION_KEY_MAP m
WHERE d.WORK_TYPE_SK IS NULL AND m.DIMENSION_NAME = 'WORK_TYPE' AND m.BUSINESS_KEY = TO_VARCHAR(d.WORK_TYPE_KEY);
UPDATE PROJECT_DW.DIM_ACCESS_STATUS d SET ACCESS_STATUS_SK = m.SURROGATE_KEY
FROM PROJECT_DW.DIMENSION_KEY_MAP m
WHERE d.ACCESS_STATUS_SK IS NULL AND m.DIMENSION_NAME = 'ACCESS_STATUS' AND m.BUSINESS_KEY = TO_VARCHAR(d.ACCESS_STATUS_KEY);
UPDATE PROJECT_DW.DIM_AUTHOR d SET AUTHOR_SK = m.SURROGATE_KEY
FROM PROJECT_DW.DIMENSION_KEY_MAP m
WHERE d.AUTHOR_SK IS NULL AND m.DIMENSION_NAME = 'AUTHOR' AND m.BUSINESS_KEY = TO_VARCHAR(d.AUTHOR_KEY);
UPDATE PROJECT_DW.DIM_INSTITUTION d SET INSTITUTION_SK = m.SURROGATE_KEY
FROM PROJECT_DW.DIMENSION_KEY_MAP m
WHERE d.INSTITUTION_SK IS NULL AND m.DIMENSION_NAME = 'INSTITUTION' AND m.BUSINESS_KEY = TO_VARCHAR(d.INSTITUTION_KEY);

-- Retain explicit date/status business keys for fact-to-dimension lookup.
UPDATE PROJECT_DW.FACT_PUBLICATION
SET PUBLICATION_DATE_KEY = TRY_TO_NUMBER(REPLACE(PUBLICATION_DATE, '-', ''))
WHERE PUBLICATION_DATE_KEY IS NULL
  AND REGEXP_LIKE(PUBLICATION_DATE, '^\d{4}-\d{2}-\d{2}$');
UPDATE PROJECT_DW.FACT_PUBLICATION SET PUBLICATION_DATE_KEY = 0
WHERE PUBLICATION_DATE_KEY IS NULL;

UPDATE PROJECT_DW.FACT_WORK_SNAPSHOT
SET ACCESS_STATUS_KEY = LOWER(TRIM(OA_STATUS))
WHERE ACCESS_STATUS_KEY IS NULL AND OA_STATUS IS NOT NULL;

-- Backfill crosswalk, facts and bridges from their retained business keys.
UPDATE PROJECT_DW.WORK_SOURCE_XW x SET WORK_SK = d.WORK_SK
FROM PROJECT_DW.DIM_WORK d WHERE x.WORK_SK IS NULL AND x.WORK_KEY = d.WORK_KEY;

UPDATE PROJECT_DW.FACT_PUBLICATION f SET WORK_SK = d.WORK_SK
FROM PROJECT_DW.DIM_WORK d WHERE f.WORK_SK IS NULL AND f.WORK_KEY = d.WORK_KEY;
UPDATE PROJECT_DW.FACT_PUBLICATION f SET WORK_TYPE_SK = d.WORK_TYPE_SK
FROM PROJECT_DW.DIM_WORK_TYPE d WHERE f.WORK_TYPE_SK IS NULL AND f.WORK_TYPE_KEY = d.WORK_TYPE_KEY;
UPDATE PROJECT_DW.FACT_PUBLICATION f SET VENUE_SK = d.VENUE_SK
FROM PROJECT_DW.DIM_VENUE d WHERE f.VENUE_SK IS NULL AND f.VENUE_KEY = d.VENUE_KEY;
UPDATE PROJECT_DW.FACT_PUBLICATION f SET ACCESS_STATUS_SK = d.ACCESS_STATUS_SK
FROM PROJECT_DW.DIM_ACCESS_STATUS d WHERE f.ACCESS_STATUS_SK IS NULL AND f.ACCESS_STATUS_KEY = d.ACCESS_STATUS_KEY;
UPDATE PROJECT_DW.FACT_PUBLICATION f SET PUBLICATION_DATE_SK = d.DATE_SK
FROM PROJECT_DW.DIM_DATE d WHERE f.PUBLICATION_DATE_SK IS NULL AND f.PUBLICATION_DATE_KEY = d.DATE_KEY;

UPDATE PROJECT_DW.FACT_WORK_SNAPSHOT f SET WORK_SK = d.WORK_SK
FROM PROJECT_DW.DIM_WORK d WHERE f.WORK_SK IS NULL AND f.WORK_KEY = d.WORK_KEY;
UPDATE PROJECT_DW.FACT_WORK_SNAPSHOT f SET SNAPSHOT_DATE_SK = d.DATE_SK
FROM PROJECT_DW.DIM_DATE d WHERE f.SNAPSHOT_DATE_SK IS NULL AND f.SNAPSHOT_DATE_KEY = d.DATE_KEY;
UPDATE PROJECT_DW.FACT_WORK_SNAPSHOT f SET ACCESS_STATUS_SK = d.ACCESS_STATUS_SK
FROM PROJECT_DW.DIM_ACCESS_STATUS d WHERE f.ACCESS_STATUS_SK IS NULL AND f.ACCESS_STATUS_KEY = d.ACCESS_STATUS_KEY;

UPDATE PROJECT_DW.FACT_CITATION f SET WORK_SK = d.WORK_SK
FROM PROJECT_DW.DIM_WORK d WHERE f.WORK_SK IS NULL AND f.WORK_KEY = d.WORK_KEY;
UPDATE PROJECT_DW.FACT_CITATION f SET CITED_WORK_SK = d.WORK_SK
FROM PROJECT_DW.DIM_WORK d WHERE f.CITED_WORK_SK IS NULL AND f.CITED_WORK_KEY = d.WORK_KEY;

UPDATE PROJECT_DW.BRIDGE_WORK_TOPIC b SET WORK_SK = w.WORK_SK
FROM PROJECT_DW.DIM_WORK w WHERE b.WORK_SK IS NULL AND b.WORK_KEY = w.WORK_KEY;
UPDATE PROJECT_DW.BRIDGE_WORK_TOPIC b SET TOPIC_SK = t.TOPIC_SK
FROM PROJECT_DW.DIM_TOPIC t WHERE b.TOPIC_SK IS NULL AND b.TOPIC_KEY = t.TOPIC_KEY;
UPDATE PROJECT_DW.BRIDGE_WORK_AUTHOR b SET WORK_SK = w.WORK_SK
FROM PROJECT_DW.DIM_WORK w WHERE b.WORK_SK IS NULL AND b.WORK_KEY = w.WORK_KEY;
UPDATE PROJECT_DW.BRIDGE_WORK_AUTHOR b SET AUTHOR_SK = a.AUTHOR_SK
FROM PROJECT_DW.DIM_AUTHOR a WHERE b.AUTHOR_SK IS NULL AND b.AUTHOR_KEY = a.AUTHOR_KEY;
UPDATE PROJECT_DW.BRIDGE_WORK_INSTITUTION b SET WORK_SK = w.WORK_SK
FROM PROJECT_DW.DIM_WORK w WHERE b.WORK_SK IS NULL AND b.WORK_KEY = w.WORK_KEY;
UPDATE PROJECT_DW.BRIDGE_WORK_INSTITUTION b SET INSTITUTION_SK = i.INSTITUTION_SK
FROM PROJECT_DW.DIM_INSTITUTION i WHERE b.INSTITUTION_SK IS NULL AND b.INSTITUTION_KEY = i.INSTITUTION_KEY;
UPDATE PROJECT_DW.BRIDGE_WORK_INSTITUTION b SET AUTHOR_SK = a.AUTHOR_SK
FROM PROJECT_DW.DIM_AUTHOR a WHERE b.AUTHOR_SK IS NULL AND b.AUTHOR_KEY = a.AUTHOR_KEY;

-- Replace null publication date references (partial/missing dates) with the
-- stable unknown-date surrogate while retaining PUBLICATION_DATE as provenance.
UPDATE PROJECT_DW.FACT_PUBLICATION f SET PUBLICATION_DATE_SK = d.DATE_SK
FROM PROJECT_DW.DIM_DATE d
WHERE f.PUBLICATION_DATE_SK IS NULL AND d.DATE_KEY = 0;
